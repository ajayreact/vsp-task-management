        Review the call together using the review questions.
        Swap roles and repeat.
        If possible, and with permission, record practice calls for review.

        Practice scenarios
        Scenario one. A recent graduate in computer science with an EAD starting next month, open to relocation, for the Charlotte Java role.
        Scenario two. A candidate who says I already have an employer, but is waiting for a project.
        Scenario three. A cautious candidate who asks whether your company is real and E-Verified.
        Scenario four. A candidate who asks you to guarantee H-1B.
        Scenario five. A candidate who says the rate is too low, comparing with a C2C rate.
        Scenario six. A candidate who hesitates to share their EAD.
        Scenario seven. A candidate with good skills but poor availability because of planned travel.

        What to practise in every call
        A clear recruiter introduction and permission.
        An approved company introduction.
        A clear opportunity explanation.
        Structured screening: location, relocation, education, graduation, experience, stack, current project, visa status and EAD dates, availability, rate and webcam readiness.
        Honest objection handling.
        A professional closing with next steps.

