        Learning objective
        Practise complete recruiter calls through structured mock calls, and use self-review and feedback to improve.

        What you need to know
        Mock calling means practising calls with a colleague, a trainer or by yourself before speaking with real candidates. It builds confidence, improves clarity and prepares you for difficult moments. The best recruiters practise regularly, even after years of experience.

        How to run a mock call
        Choose a scenario and a role card for the candidate.
        One person plays the recruiter, the other plays the candidate.
