        Did I introduce myself and ask permission?
        Did I use approved wording for company facts, E-Verify, sponsorship and rates?
        Did I ask approved work authorization questions in the same way as with every candidate?
        Did I avoid promises and legal advice?
        Did I listen more than I spoke?
        Did I summarise and agree on next steps?
        Did I speak clearly and at a steady pace?

        Giving feedback to colleagues
        Start with what went well.
        Give one or two specific improvements.
        Suggest a better phrase or approach.
