        'Objection: "Your rate is too low"' => <<<'TEXT'
        Learning objective
        Respond professionally when a candidate says the rate is too low, by understanding their expectations, explaining the approved rate honestly and escalating appropriately.

        What you need to know
        Rate objections are common. Sometimes the candidate's expectation is based on a different location, a different engagement type, information from friends, or another offer. Sometimes the approved rate is genuinely low for the market. Your job is to understand the gap, explain honestly, and check flexibility only through your lead.

        Step one: acknowledge
        I understand, and thank you for telling me directly.

        Step two: clarify the expectation
        What rate were you expecting for this role?
        Is that hourly on W2?
        What is your expectation based on, for example another offer or a different location?

        Step three: compare like with like
        Hourly W2 and annual salary are different.
        W2 and C2C rates are not comparable in the same way.
        Rates differ by city and cost of living.
        Explain these differences simply, without lecturing.

        Step four: explain the role's value honestly
        Duration and possible extension, without guarantees.
        The client and the technologies, which may help their career.
        The location and work mode.
        Benefits, only if approved. Company-specific process: benefits and any rate split explanation must come from HR or authorized personnel.

        Step five: escalate when appropriate
        If the gap is small and the candidate is strong, ask your lead whether any flexibility exists.
        Never promise a higher rate before approval.
        Inform the candidate of the answer promptly.

        When the gap cannot be closed
        Thank the candidate and respect the decision.
        Record their expected rate, so that you can match them with better-paying roles later.

        Sample response
        I understand. The approved rate for this role is the range I mentioned, on W2 hourly. The project is twelve months with a banking client and uses Spring Boot and Kafka, which is valuable experience. I can check with my lead whether there is any flexibility, but I cannot promise a change. Would you like me to check?

        Practical example
        A candidate compares your W2 hourly rate with a friend's C2C rate. You explain the difference simply: C2C rates are paid to a business that covers its own taxes and costs, while W2 rates are paid to an employee with taxes withheld. You suggest that he ask payroll or a tax professional for details. He understands and agrees to continue.

        Recruiter checklist
        Understand the expectation and its basis.
        Compare like with like.
        Explain value honestly.
        Escalate flexibility requests, never promise.

        Common mistakes
        Promising a higher rate.
        Arguing with the candidate.
        Sharing bill rates or margins.

        From the company cheat sheet
        Objection five: Your hourly rate or split is too low. Other vendors are offering me more.
        The hidden concern: the candidate is comparing gross percentages or hourly rates without accounting for support, hidden fees or bench delays.
        The source response, in summary: I understand that a higher rate sounds attractive on paper. However, a high rate means very little if a vendor takes months to find you a project. Our package includes dedicated technical interview preparation and marketing support from a full sales team. We focus on continuous employment and long-term career growth. Let us look at the full package value together.
        Keep the like-for-like comparison and the full-package approach. Describe only the support the company actually provides, confirmed by HR, and do not suggest that other vendors are slow or charge hidden fees unless you have facts. The word split refers to a percentage arrangement between consultant and employer. Explain any such arrangement only as HR has approved it.

        Key takeaway
        Handle rate objections with facts, fairness and approved flexibility only. Respect the candidate's decision.
