        What you need to know
        Many OPT candidates already work with an employer, sometimes on a project and sometimes waiting for one. When a candidate says I already have an employer, it can mean several things: they are happy and not looking, they are employed but open to better roles, or they are registered with another company but not yet placed. Your goal is to understand which situation applies, without pressure or criticism.

        Step one: acknowledge
        That is great to hear, congratulations.
        I completely understand.

        Step two: clarify politely
        Are you currently working on a project, or waiting for one?
        Are you open to hearing about other opportunities, or are you settled for now?
        If the right role came along, what would it need to offer?

        Step three: respond based on the situation
        Happy and working: Thank them, ask whether you can stay in touch, and ask for referrals.
        Working but open: Explain the role briefly and let them decide.
        Registered but not placed: Explain your role clearly. Respect any agreements they have. Do not criticise the other company.

        Agreements and ethics
        If the candidate mentions an agreement with their current employer, do not interpret it or tell them to ignore it. Suggest that they review it, and inform your lead.
        Do not submit a candidate who is already submitted to the same client by another company.
        Company-specific process: questions about changing employers during OPT or STEM OPT involve reporting and training plan responsibilities handled by the candidate, the DSO and HR. Refer such questions to them and verify with HR or authorized personnel.

        Sample response
        That is great to hear, congratulations on your project. I really appreciate you telling me. If it is all right, I will keep your profile in mind for the future. Also, if you know any friends with Java experience who are looking, I would be happy to help them.

        What not to say
        Your current employer is not good.
        You should leave immediately.
        We can pay much more, before checking the facts.

