        Answer H-1B questions honestly, without guarantees, using only your company's approved position.

        What you need to know
        Many OPT candidates hope to move to H-1B status in the future. They often ask recruiters about H-1B sponsorship. The H-1B process usually involves an employer filing on the candidate's behalf, a selection process when demand exceeds the annual limit, and approval by U.S. Citizenship and Immigration Services. No recruiter or employer can guarantee selection or approval.

        What you must never say
        We guarantee H-1B.
        Your H-1B will definitely be approved.
        If you join us, you will get H-1B next year.
        We have a hundred percent success rate.
        These statements are false or misleading, can harm the candidate's decisions, and can create serious legal risk for your company.

        What you can say
        Company-specific process: your company's position on H-1B sponsorship must come from HR or authorized personnel. Verify the approved wording before using it. Examples of honest responses include:
        H-1B sponsorship decisions are made by our management based on company policy, project needs and performance. I can connect you with our HR team to explain our current policy.
        No company can guarantee H-1B selection or approval, because the government decides. I can share our company's approved policy, and HR can answer detailed questions.

        Handling follow-up questions
        How many people did you sponsor last year? Share only approved figures, or refer to HR.
        Who pays the fees? Refer to HR. Never invent answers.
        Can I stay on STEM OPT while waiting? Refer to the DSO and HR.

        Keeping the conversation balanced
        Acknowledge that H-1B is important to the candidate.
        Focus on the current opportunity: the role, skills and experience it offers.
        Let the candidate make an informed choice.

        Sample response
        I understand that H-1B is important for your long-term plans. I want to be completely honest with you. No company can guarantee H-1B, because the selection and approval are decided by the government. Our HR team can explain our company's sponsorship policy in detail. Would you like me to arrange that?

        Practical example
        A candidate says another company promised him H-1B if he joins. You do not criticise the other company. You explain that guarantees are not possible, share your approved policy, and offer an HR conversation. He thanks you for being honest and agrees to continue with the screening.

        Recruiter checklist
        Never guarantee H-1B.
        Use only the approved company position.
        Refer detailed questions to HR and the DSO.
        Refocus on the current role.

        Common mistakes
        Making promises to win the candidate.
        Guessing sponsorship numbers or fees.
        Criticising other companies' claims.

        From the company cheat sheet
        Objection four: Can you guarantee H-1B sponsorship next year?
        The hidden concern: the candidate wants long-term immigration stability and does not want to be treated as temporary labour.
        The source response opens correctly: the H-1B process is an official lottery managed by the U.S. government, so no company can legally guarantee a selection. Use that sentence.
