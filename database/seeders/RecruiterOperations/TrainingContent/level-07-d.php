        Learning objective
        Understand a simple, respectful method to handle candidate objections honestly, without pressure or false promises.

        What you need to know
        An objection is a concern or reason a candidate gives for not moving forward. Objections are normal. They often show that the candidate is thinking seriously about the opportunity. Good objection handling is not about winning an argument. It is about understanding the concern, sharing accurate information, and letting the candidate make an informed choice.

        The four-step method
        Listen. Let the candidate explain the concern fully, without interrupting.
        Acknowledge. Show that you understand: That is a fair concern.
        Clarify. Ask questions to understand the real reason: Could you tell me more about what worries you?
        Respond. Share accurate, approved information, or offer to find out. Then ask whether that addresses the concern.

        Common objections in OPT recruiting
        I already have an employer.
        Is your company real?
        Why do you need my EAD or I-20?
        Can you guarantee H-1B?
        Your rate is too low.
        I do not want to relocate.
        I am not interested in contract roles.
        I have had a bad experience with staffing companies.
        The following lessons cover the first five in detail.

        Principles for honest objection handling
        Never lie or exaggerate to overcome an objection.
        Never promise outcomes, such as offers, extensions, rates or sponsorship.
        Never criticise other companies or the candidate's choices.
        Use only approved company information. Company-specific process: answers about your company's E-Verify enrollment, sponsorship policy, benefits and history must come from HR or authorized personnel.
        Accept no when the candidate decides.

        Tone during objections
        Stay calm and friendly, even if the candidate sounds suspicious or annoyed.
        Do not take objections personally.
        Speak slowly and clearly.

        When you do not know the answer
        Say: I want to give you accurate information, so let me confirm with our HR team and get back to you by tomorrow. Then do it.

        Practical example
        A candidate says: I am not interested in contract roles. You acknowledge the concern and ask why. She explains that she worries about job security. You explain honestly that this is a twelve-month W2 contract with possible extension, that extension is not guaranteed, and that W2 consultants are employees of your company during the assignment. She thinks about it and agrees to discuss it further.

        Recruiter checklist
        Listen fully.
        Acknowledge the concern.
        Ask clarifying questions.
        Respond with accurate, approved information.
        Respect the final decision.

        Common mistakes
        Interrupting with a prepared answer.
        Making promises to overcome an objection.
        Pushing after the candidate has said no.

        From the company training material: the objection cheat sheet
