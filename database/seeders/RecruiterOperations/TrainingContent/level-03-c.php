        Eligibility for unemployment benefits depends on state law and many factors, and can involve immigration considerations. Recruiters must never advise anyone on whether to apply for unemployment benefits. Also remember that unemployment benefits are different from the OPT unemployment day limits discussed in Level 2.

        Practical example
        A consultant asks: Why is federal unemployment tax not on my pay stub? You explain: FUTA is paid entirely by the employer, so it is not deducted from your pay.

