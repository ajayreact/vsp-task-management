        Important note
        International student offices advise students on immigration matters. Recruiters do not give immigration advice and should not ask these offices to act on a candidate's behalf. Follow company policy.

        Learning objective
        Understand the role of international student offices and how recruiters should, and should not, interact with them.

        What you need to know
        The international student office at a university supports students on F-1 and other visas. It includes designated school officials, called DSOs, who manage SEVIS records, recommend OPT, and update records for STEM OPT. Students rely on these offices for official guidance about their status.

        What international student offices do
        Advise students on maintaining status.
        Recommend OPT and update records in SEVIS.
        Review and support STEM OPT applications, including the I-20 update.
        Provide workshops on OPT, STEM OPT and employment rules.
        Answer students' questions about reporting requirements.

        How recruiters relate to international student offices
        Recruiters usually do not contact these offices directly about individual students. The student contacts their own DSO.
        Some offices publish information for employers. Read it to understand the university's guidance.
        Some offices hold employer information sessions about hiring international students. Attend only if approved and invited.
        Company-specific process: if your HR team needs to communicate with a DSO, for example about a STEM OPT training plan, HR or authorized personnel handle it, not recruiters.

        Referring candidates to their DSO
        When candidates ask status questions, say: Your DSO is the best person to guide you on that.
        Encourage candidates to check their reporting responsibilities with the DSO when they start a job or change employers.

        What recruiters must not do
        Do not contact a DSO pretending to represent the student.
        Do not ask a DSO for a student's information.
        Do not tell students to avoid their DSO.

