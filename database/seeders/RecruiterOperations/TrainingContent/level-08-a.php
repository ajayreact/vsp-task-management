        'Follow-Up' => <<<'TEXT'
        Learning objective
        Follow up on outreach effectively, so that initial contacts become lasting relationships and steady sources of candidates.

        What you need to know
        Most outreach does not get a reply on the first attempt. People are busy, emails are missed, and timing may not be right. Polite, well-timed follow-up often makes the difference. At the same time, too much follow-up feels like pressure. A good balance is two or three follow-ups, spaced over a few weeks.

        Follow-up timing
        First follow-up: about five to seven business days after the first message.
        Second follow-up: about one to two weeks later.
        Final message: a polite note that you will not follow up further, and that they can contact you anytime.
        For universities, consider the academic calendar. Avoid exam weeks and holidays.

        Follow-up content
        Refer to your earlier message briefly.
        Add something new and useful, such as a new role or an event date.
        Keep it shorter than the first message.
        Repeat the simple request.

        Sample follow-up
        Hello, I wanted to follow up on my message last week about sharing data analyst openings with your members. We have two new junior roles in Texas this month. Please let me know if this would be helpful. Thank you, Anita.

        Following up after a relationship starts
        Thank organisations after events or newsletters.
        Share results, such as students who were placed, only with consent and within privacy rules.
        Check in each semester.
        Keep your contact information current with them.

        Following up with candidates from outreach
        Respond to every interested candidate within one business day.
        Schedule screening calls promptly.
        Keep candidates informed even if there is no suitable role yet.

        Recording follow-up
        Record each contact and follow-up date.
        Set reminders for the next step.
        Note outcomes, such as no reply, declined or interested.

        Practical example
        A career center does not reply to your first email. After a week, you send a short follow-up mentioning your upcoming registration for the spring career fair. The career center replies with the registration link. You register with your lead's approval and thank them.

        Recruiter checklist
        Follow up two or three times, spaced well.
        Add new value in each follow-up.
        Respect calendars and decisions.
        Record and schedule every follow-up.

        Common mistakes
        Giving up after one message.
        Sending daily follow-ups.
        Forgetting to thank contacts after help.

        Source note
        The company training documents cover follow-up with candidates, but not with universities or student organisations. This lesson is based on general practice and needs additional approved training content.

        Key takeaway
        Polite, timely and valuable follow-up turns first contacts into relationships.
