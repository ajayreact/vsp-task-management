        Learning objective
        Research universities systematically to identify where suitable OPT candidates study, and plan outreach that fits each university's calendar and rules.

        What you need to know
        Not every university is equally useful for every requirement. Some have large computer science and data programs with many international students. Others focus on different fields. Good research helps you spend your time on universities where your requirements match the students' skills, and helps you approach each university correctly.

        What to research
        Programs offered, such as computer science, information systems, data science, business analytics, cybersecurity and engineering.
