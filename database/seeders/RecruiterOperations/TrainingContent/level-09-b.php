        This lesson covers process awareness only, not tax or payroll advice. Follow company policy and confirm with payroll or HR.

        Learning objective
        Complete a payroll handoff that is accurate, complete and timely, using your company's approved process.

        What you need to know
        Level 6 explained why payroll depends on accurate information. This lesson focuses on completing the handoff itself. A complete payroll handoff allows payroll to set up the consultant correctly before the first pay period, avoiding delays and corrections.

        Payroll handoff checklist
        Consultant legal name, matching official documents.
        Contact details.
        Employee type, such as W2 hourly or W2 salaried.
        Approved pay rate or salary.
        Overtime eligibility and rules, if approved.
        Start date.
        Work location: street address or city and state where the consultant physically works.
        Home address, especially for remote or hybrid consultants.
        Client, vendor and project details needed for billing and timesheets.
        Timesheet process and approver, if known.
        Planned changes, such as relocation dates.
        Company-specific process: the exact fields and system used for the payroll handoff are set by payroll. Verify with HR or authorized personnel.

        Timing
        Complete the handoff as soon as the offer is accepted and terms are approved.
        Update payroll immediately if anything changes before the start.

        Accuracy checks
        Compare the rate with the approved offer.
        Compare the start date with the offer letter and the EAD start date.
        Check addresses for spelling and correct state.

        After the handoff
        Confirm that payroll received it.
        Answer payroll's questions quickly.
        Refer the consultant's pay questions to payroll.

        Practical example
        Your consultant will work hybrid from Charlotte, North Carolina, but will live in Fort Mill, South Carolina. You record both addresses in the handoff and note that she will commute across state lines. Payroll thanks you, because this affects state tax setup.

        Recruiter checklist
        Complete every field accurately.
        Include work and home addresses.
        Hand off as soon as terms are approved.
        Update payroll on every change.

        Common mistakes
        Entering the client's headquarters as the work location.
        Missing the home address for remote consultants.
        Delaying the handoff until the first week.

        Key takeaway
        A complete and timely payroll handoff means the consultant is paid correctly from the first pay period.
