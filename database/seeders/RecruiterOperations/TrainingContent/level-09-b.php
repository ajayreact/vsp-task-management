        Learning objective
        Understand the full onboarding journey at an awareness level, so that you can prepare candidates, anticipate delays and support HR effectively.

        What you need to know
        Onboarding begins when a candidate accepts an offer and ends when they are fully set up and working. It involves HR, payroll, the vendor, the client and the consultant. Recruiters do not run onboarding, but they are often the person the candidate trusts most. Understanding the journey helps you keep the candidate calm and prepared.

        A typical onboarding journey
        Offer acceptance and offer letter.
        Employment agreement and company policies.
        Employment eligibility verification through Form I-9 and, where applicable, E-Verify.
