        Understand the documentation side of the offer process, including offer letters, agreements, conditions and records.

        What you need to know
        Level 6 explained how to communicate an offer. This lesson focuses on the documents and records involved. An offer becomes formal through written documents issued by HR or authorized personnel. These documents must match what was agreed and approved.

        Offer documents may include
        An offer letter stating the role, employer, start date, pay, work location and engagement type.
        An employment agreement with company terms and policies.
        Conditions, such as background check clearance and employment eligibility verification.
        Client or project assignment details.
        Company-specific process: the documents and their wording are prepared by HR or authorized personnel. Recruiters must not create, edit or sign offer documents unless authorised. Verify with HR or authorized personnel.

        Recruiter responsibilities
        Pass the approved offer details to HR accurately.
        Review the offer details HR sends you, if your process allows, and report any differences from what was agreed.
        Tell the candidate when to expect the documents.
        Remind the candidate to read documents carefully and ask HR questions.
        Record the date the candidate signed and returned documents, if your process requires it.

        When the candidate has questions about documents
        Questions about terms, legal language, non-compete or other clauses go to HR.
        Do not interpret agreement terms.
        Encourage the candidate to read everything before signing.

        When details do not match
        If the offer letter shows a different rate, start date or location from what was agreed, inform HR immediately before the candidate signs.
        Never tell the candidate to sign and fix it later.

        Offer records
        Keep the approved terms, acceptance confirmation and document dates in the approved system.
        These records protect both the candidate and the company.

        Practical example
        HR sends the offer letter for review. You notice that the start date says June 1, but the agreed and approved start date is June 3, after the candidate's EAD start date. You inform HR immediately. HR corrects it before sending the letter to the candidate.

        Recruiter checklist
        Pass accurate approved terms to HR.
        Check offer documents for differences when allowed.
        Refer document questions to HR.
        Record acceptance and signature dates.

        Common mistakes
        Creating offer documents yourself.
        Interpreting agreement clauses.
        Ignoring small differences in dates or rates.

        Key takeaway
        Offer documents must match approved terms exactly. Check carefully, report differences, and leave the documents to HR.
