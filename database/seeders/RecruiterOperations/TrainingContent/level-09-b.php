        Company-specific process: final start date approval rules are set by HR. Verify with HR or authorized personnel.

        Communicating the start date
        Use the full date with the month name and day of the week, for example Wednesday, June 3, 2026.
        Include the start time and time zone.
        Include the location or meeting link and the first-day contact.
        Send it in writing.

        When the start date changes
        Inform HR, payroll, the vendor and the candidate promptly.
        Check the new date against authorization again.
        Record the change and the reason.

        Never start early
        A consultant must not begin any work, including training or system setup involving work, before their authorization start date and before HR confirms they are ready. If anyone asks for an earlier start, involve HR.

