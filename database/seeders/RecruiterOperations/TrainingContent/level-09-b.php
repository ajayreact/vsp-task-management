        'Work-State Information' => <<<'TEXT'
        Important note
        State tax and employment rules vary and change. Recruiters do not give tax or legal advice. Verify current requirements and confirm with payroll, HR or compliance.

        Learning objective
        Understand why the work state matters and how to record and report work-state information accurately.

        What you need to know
        In the United States, each state has its own rules for income tax, unemployment insurance, paid leave and some employment laws. Some states have no state income tax, and some cities have local taxes. Which rules apply often depends on where the employee physically works, and sometimes where they live. That is why payroll and HR need accurate work-state information.

        Work-state situations
        Onsite: the consultant works at the client location in one state.
        Hybrid: the consultant works partly at the client office and partly at home, sometimes in different states.
        Remote: the consultant works from home, which may be in a different state from the client.
        Travel: the consultant works temporarily in other states.
        Relocation: the consultant moves to a new state during the assignment.

        What to record
        The state and city of the work location.
        The state and city of the home address.
        For hybrid roles, the number of office days.
        Planned moves and their dates.
        Temporary work in other states, if known.

        Reporting changes
        Consultants must inform the company before moving or working from a different state. Remind them of this.
        Inform payroll and HR as soon as you learn of a change.
        Company-specific process: some companies restrict remote work to certain states. Verify with HR or authorized personnel before agreeing to any remote location.

        Answering candidate questions
        Will I pay state tax? That depends on state rules and your situation. Payroll can explain how it applies.
        Can I work remotely from another state? Please check with HR before making plans. Our company has to approve it.

        Practical example
        A remote consultant tells you she plans to move from Texas to Washington next month. You thank her, explain that HR and payroll must approve and update the work state before the move, and inform both teams the same day with the planned date.

        Recruiter checklist
        Record work and home states accurately.
        Remind consultants to report moves in advance.
        Report changes to payroll and HR immediately.
        Never approve remote locations yourself.

        Common mistakes
        Recording the client's state for remote consultants.
        Learning about moves after they happen.
        Telling consultants a state has no tax impact.

        Key takeaway
        The work state drives taxes and compliance. Record it accurately and report changes before they happen.
