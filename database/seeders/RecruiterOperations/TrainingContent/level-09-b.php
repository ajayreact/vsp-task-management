        Recruiter checklist
        Check start dates against authorization.
        Confirm with all parties.
        Communicate in writing with full details.
        Report changes immediately.

        Common mistakes
        Agreeing to client dates without checking authorization.
        Using unclear date formats.
        Allowing early starts for training.

        Key takeaway
        A correct start date is confirmed with everyone, checked against authorization and communicated clearly in writing.
