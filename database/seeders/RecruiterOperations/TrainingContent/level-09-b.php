        'Internal Escalation' => <<<'TEXT'
        Learning objective
        Know when and how to escalate issues internally, so that risks are handled by the right people quickly and correctly.

        What you need to know
        Escalation means passing an issue to someone with the authority or expertise to resolve it. Escalating is not a failure. It is part of a recruiter's responsibility, especially in areas such as immigration, payroll, legal agreements and candidate complaints, where recruiters must not make decisions.

        When to escalate
        Work authorization questions or inconsistencies, such as different names or unclear dates.
        Requests for legal, immigration or tax advice.
        Candidate complaints or serious concerns.
        Suspected fraud, such as fake documents, interview impersonation or false resumes.
        Offer or payroll errors.
        Start date conflicts with authorization dates.
        Requests from vendors or clients that seem improper.
        Any situation where you are unsure.

        Who to escalate to
        Your team lead or manager for process and priority issues.
        HR for documentation, onboarding, authorization and employee concerns.
        Payroll for pay, tax forms and work-state questions.
        Compliance or authorized personnel for legal or regulatory concerns.
        Company-specific process: your company's escalation contacts and channels are defined by management. Verify with HR or authorized personnel.

        How to escalate well
        Escalate early, before the issue grows.
        Use the approved channel, such as email or the company system.
        State the facts clearly: who, what, when, and what you need.
        Attach relevant records, using secure channels.
        Do not include assumptions as facts.
        Tell the candidate, where appropriate, that the right team is reviewing the question.

        Sample escalation message
        Subject: EAD date conflict for June 1 start, Java developer, Charlotte.
        The client requested a June 1 start for our selected candidate. Her EAD start date, as recorded on May 10, is June 3. Please confirm whether we should propose June 3 to the vendor. The vendor needs an answer by Wednesday.

        After escalating
        Follow up if there is no reply by the needed time.
        Record the decision and act on it.
        Do not act on your own while the issue is pending.

        Practical example
        During onboarding, a candidate's background check shows a different employer name for one role on his resume. You do not confront him or decide. You escalate to HR with the facts. HR reviews and finds that the company was renamed after an acquisition. The issue is resolved.

        Recruiter checklist
        Recognise escalation situations.
        Escalate early to the right person.
        State facts clearly and securely.
        Follow up and record decisions.

        Common mistakes
        Waiting until the problem is urgent.
        Trying to resolve legal or HR issues yourself.
        Escalating with vague or emotional messages.

        Key takeaway
        Good escalation is early, factual and directed to the right person. It protects candidates, consultants and your company.
