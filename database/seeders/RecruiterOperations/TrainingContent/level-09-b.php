        Late responses to HR requests.
        Background check delays, especially for international employment or education.
        Client system access delays.
        Start date changes from the client.
        Pending authorization approvals.

        Managing delays
        Inform your lead and the vendor early.
        Keep the candidate informed and reassured.
        Never promise a new date until it is confirmed.

        Practical example
