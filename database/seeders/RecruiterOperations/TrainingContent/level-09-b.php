        Why is this deduction on my pay statement?
        When will my first payment arrive?
        How do I change my direct deposit?
        Why is my state tax different from my friend's?

        Explaining gross and net pay simply
        Gross pay is the total earned before deductions.
        Net pay is the amount received after taxes and other deductions.
        Payroll can explain the deductions on each pay statement.

        Timesheets
        Explain that hourly consultants must submit accurate timesheets on time, following the company and client process.
        Remind them that late or incorrect timesheets can delay pay.
        Never ask a consultant to record hours they did not work, or to leave out hours they did work.

        Practical example
        A new consultant asks when he will be paid. You know the pay frequency is biweekly, but not the exact first pay date. You say: Our pay is biweekly. Payroll will confirm your first pay date, and I will ask them to contact you today. You then connect him with payroll.

        Recruiter checklist
        Share only approved pay information.
        Explain gross and net pay simply.
        Remind consultants about accurate timesheets.
        Refer detailed questions to payroll.

        Common mistakes
        Estimating net pay.
        Guessing first pay dates.
        Encouraging inaccurate timesheets.

        Key takeaway
        Share approved pay basics clearly, and connect consultants with payroll for everything else.
