        Learning objective
        Understand the main regions of the United States and how regions help you plan sourcing, relocation discussions and scheduling.

        What you need to know
        Americans often describe locations by region. Regions are not official boundaries, but they are widely used in conversation and in job descriptions.

        The main regions
        The Northeast includes New York, New Jersey, Pennsylvania, Massachusetts, Connecticut, Rhode Island, Vermont, New Hampshire and Maine. It is home to major finance, insurance and healthcare clients.
        The Southeast, often called the South, includes Florida, Georgia, North Carolina, South Carolina, Virginia, Tennessee, Alabama and nearby states. Charlotte, Atlanta and Tampa are common IT locations.
        The Midwest includes Illinois, Ohio, Michigan, Indiana, Wisconsin, Minnesota, Iowa, Missouri and nearby states. Chicago is the largest hub.
        The Southwest includes Texas, Arizona, New Mexico and Oklahoma. Texas is one of the largest IT staffing markets.
        The West includes California, Washington, Oregon, Colorado, Utah, Nevada, Idaho, Montana and Wyoming. Technology companies are concentrated around San Francisco, San Jose and Seattle.
        Alaska and Hawaii are separate from the mainland and sit in their own time zones.

        Other useful terms
        East Coast means the states along the Atlantic Ocean.
        West Coast means California, Oregon and Washington.
        The Bay Area means the region around San Francisco, including San Jose and Silicon Valley.
        The Tri-State Area usually means New York, New Jersey and Connecticut.
        The DMV area means D.C., Maryland and Virginia.

        Why regions matter to recruiters
        Regions help you think about relocation. A candidate in New Jersey may consider a role in New York or Pennsylvania more easily than one in California.
        Regions help with time zones. The East Coast is three hours ahead of the West Coast.
        Regions help with sourcing. If a requirement is in Dallas, candidates already in Texas or nearby states may be the best starting point.

        Practical example
        A client in Atlanta needs a consultant onsite in four weeks. You first look for candidates in Georgia, then in nearby Southeast states such as Tennessee, Alabama, North Carolina and South Carolina, before searching the whole country.

        Recruiter checklist
        Identify the region of every requirement.
        Start sourcing close to the work location when onsite work is required.
        Use regions to plan call times across the country.

        Common mistakes
        Assuming the Midwest is in the middle of the country in every sense. It actually stretches from Ohio to the Dakotas.
        Treating a long-distance move as easy because two states are in the same region. Distances in the U.S. can be very large.

        Source note
        The company training material groups states by time zone, not by region. The regions in this lesson follow common U.S. usage. This lesson is based on general reference information and needs review and approval by the training manager.

        Key takeaway
        Regions give you a quick mental map of the U.S. Use them to plan sourcing, relocation conversations and scheduling.
