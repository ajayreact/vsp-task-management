        'Introduction to the United States' => <<<'TEXT'
        Learning objective
        By the end of this lesson you will understand the basic structure of the United States and why this knowledge matters every day in U.S. IT staffing.

        What you need to know
        The United States of America, usually called the U.S. or the USA, is a federal country made up of 50 states and the District of Columbia. The District of Columbia, written as D.C., is the national capital, Washington, D.C. It is not a state.
        The U.S. also has territories such as Puerto Rico and Guam. You will rarely see these in IT requirements, but you should know they exist.
        Each state has its own government, its own laws and, in many cases, its own payroll and tax rules. This is why recruiters always confirm the exact state where a consultant will work.
        The U.S. covers six main time zones, so a call at ten in the morning in New York is seven in the morning in California.
        English is the main business language. Most clients expect clear, polite and direct communication.

        Key concepts
        Federal means rules that apply to the whole country. State means rules that apply only inside one state.
        City and state are usually written together, for example Dallas, Texas, or Dallas, TX.
        A ZIP code is the U.S. postal code. It is five digits long and helps identify an exact location.
        Remote, hybrid and onsite describe where the work happens. Even remote roles are often tied to a specific state for payroll.
        The U.S. uses the month, day, year date format. The date 04/05 means April fifth, not the fourth of May.
        The U.S. uses dollars, miles, pounds and Fahrenheit, not rupees, kilometres, kilograms and Celsius.

        Why this matters for an OPT recruiter
        Your candidates are usually international students or recent graduates living in different U.S. states. Your clients and vendors are spread across the country. You will schedule calls across time zones, read job descriptions that mention cities and states, and pass location details to HR and payroll. Small mistakes, such as confusing a city or a date, can cause missed interviews or wrong paperwork.

        Practical example
        A job description says: Location, Charlotte, NC, hybrid, three days onsite. Start date 06/03.
        A trained recruiter reads this as Charlotte, North Carolina, in the Eastern time zone, with three office days a week, starting on June third. The recruiter then asks the candidate whether they are already in North Carolina or willing to relocate before June third.

        Recruiter checklist
        Confirm the city and the full state name for every requirement.
        Confirm the time zone before scheduling any call.
        Read every date in the U.S. month, day, year format.
        Ask whether a role is remote, hybrid or onsite.
        Note the work state accurately, because HR and payroll depend on it.

        Common mistakes
        Reading U.S. dates in the Indian day, month, year format.
        Assuming a remote role has no location requirement.
        Mixing up cities that share a name, such as Portland, Oregon, and Portland, Maine.
        Scheduling a call without checking the candidate's time zone.

        Source note
        The OPT Recruiter Training Material covers the states, their abbreviations, the time zones, the time difference from India and the phonetic alphabet, which are taught in the lessons that follow. It does not include a general introduction to the U.S. This lesson is based on general reference information and needs review and approval by the training manager.

        Key takeaway
        The U.S. is a large federal country with 50 states, several time zones and state-level rules. Accurate location, time and date details are the foundation of professional recruiting.
