        'Scenario: Recruiter Workflow Simulation' => <<<'TEXT'
        Learning objective
        Practise the complete OPT recruiter workflow from requirement to first day, combining all the skills from Levels 1 to 9.

        How to use this scenario
        Work through each stage in order. For each stage, write down what you would do, what you would record, and what could go wrong. Discuss your plan with your trainer or team. This simulation can be completed over several sessions.

        The scenario
        On Monday morning, India time, you receive a requirement for a Business Analyst with SQL skills for a retail client in Dallas, Texas, hybrid three days a week, on a twelve-month W2 contract. The vendor confirms that OPT and STEM OPT candidates are accepted. The client wants to interview within one week and start within four weeks.

        Stage one: requirement analysis
        Summarise the requirement and list your vendor questions.
        Consider time zones: what time is it in Dallas when you start work?

        Stage two: search strategy and sourcing
        Choose your channels: internal pipeline, LinkedIn, universities, communities and referrals.
        Write your primary and secondary keywords.
        Plan outreach timing in Central Time.

        Stage three: screening and interest confirmation
        Plan the screening topics.
        Plan how you will confirm interest, check for duplicate submissions and obtain the right to represent.

        Stage four: submission and interviews
        Prepare an honest submission summary.
        Plan interview scheduling, including time zones and webcam readiness.
        Plan follow-up with the vendor and the candidate.

        Stage five: offer
        The client selects your candidate. Plan how you will communicate the approved offer and confirm acceptance.
        The client asks for a start date that is two days before the candidate's EAD start date. Decide what you will do.

        Stage six: documentation and onboarding handoff
        List the information you will hand off to HR.
        Identify what HR, not you, will handle.

        Stage seven: payroll handoff
        The candidate will live in a different city from the office, but in the same state. List the payroll information you will provide.

        Stage eight: first day and follow-up
        Plan first-day confirmation and follow-up checkpoints.
        Plan when you might ask for referrals.

        Mapping to the company process
        Now repeat the simulation using the company's own process documents. For a vendor requirement, follow the US MNC Staffing steps: get the requirement from the BDM, study it two or three times, check your hotlist, mass mail your vendor list, post in a portal and search for C2C consultants, select the best one or two resumes, call and screen, confirm the rate, collect the right to represent and the submission template, call the employer for C2C consultants and sign the NDA and NCA, send the submission to the BDM, and follow up for feedback.
        For an OPT candidate, follow the End-to-End Business Process: sourcing, document collection by you, review by HR or the verification team, confirmation of genuine and valid documents, offer letter issued by HR, the E-Verify step completed by HR, payroll follow-up by you, payroll processed by the Accountant, and continued monitoring by you and the OPT Head. At each step, write down which part is yours and which belongs to HR, the Accountant or the OPT Head.

        Things that could go wrong
        The vendor goes silent after submission.
        The candidate receives a competing offer.
        The background check is delayed.
        The candidate asks a tax question.
        For each, decide how you would respond and whom you would involve.

        Reflection questions
        Which stage do you feel most confident in? Which needs more practice?
        Where in the workflow did you need to escalate?
        Where did accurate records make the biggest difference?

        Recruiter checklist
        Follow every stage in order.
        Record and hand off accurately.
        Respect compliance boundaries.
        Communicate and follow up at every step.

        Key takeaway
        The workflow brings every skill together. Practise the whole journey, and you will be ready for real requirements from first contact to first day.
