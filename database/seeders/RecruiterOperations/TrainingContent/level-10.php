        The requirement
        Junior QA Automation Engineer, Atlanta, Georgia, hybrid three days a week, twelve-month W2 contract, start in four weeks.
        Required: one or more years of test automation with Selenium and Java, API testing, and experience with an agile team.
        Preferred: CI tools such as Jenkins, and retail domain experience.
        Accepts OPT and STEM OPT candidates, as confirmed by the vendor.

        The resume summary
        Candidate name: Meera.
        Education: Master of Science in Information Systems, program ended in May this year. Bachelor of Engineering in India.
        Experience: QA engineer in India for one year and two months, manual testing with some Selenium scripts. QA intern in the United States for six months on CPT, writing Selenium tests with Java and testing REST APIs with Postman.
        Projects: a capstone project building an automation framework with Selenium, TestNG and Jenkins.
        Skills listed: Selenium, Java, Python, Postman, Jenkins, JIRA, SQL, Cypress, Appium, Kubernetes.
        Location: listed as Chicago, Illinois.
        No retail experience is mentioned.

        Practice steps
        Compare each required skill with the evidence in the resume.
        Note which preferred skills are present.
        Estimate the relevant automation experience in months, separating professional, internship and academic work.
        List the skills that appear in the skills section but not in any project or role.
        Write the questions you would ask on a screening call.
        Decide whether you would move forward to a screening call, and write a short note explaining your reasoning.

        Points to think about
