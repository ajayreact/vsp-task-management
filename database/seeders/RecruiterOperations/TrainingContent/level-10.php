        Important note
        These scenarios are for practising compliance boundaries. They are not legal advice. In real situations, follow company policy, refer questions to HR, compliance or the candidate's DSO, and escalate when uncertain.

        Learning objective
        Practise recognising immigration-related questions that fall outside a recruiter's role, and responding with appropriate referrals and escalation.

        How to use this scenario
        Read each situation. For each one, decide what you would say to the candidate, who you would refer them to, and whether you would escalate internally. Discuss your thinking with your trainer.

        The situations
        Situation one. A candidate asks: My EAD starts next week, but the client wants me to start training this Friday. Is that fine?
        Situation two. A candidate asks: How many days can I be unemployed on OPT before I have a problem?
        Situation three. A candidate asks: Does my Master's in Business Analytics qualify for STEM OPT?
        Situation four. A candidate asks: Can you fill in my I-983 for me, so that it is faster?
        Situation five. A candidate asks: I am planning to travel home next month while my STEM OPT application is pending. Will that be a problem?
        Situation six. A vendor asks you to describe a candidate's OPT as a green card so that the client accepts the profile.
        Situation seven. A candidate asks: Will your company definitely file my H-1B next year?
        Situation eight. A candidate's EAD shows a different spelling of her last name from her resume.
        Situation nine. During screening, a candidate on initial OPT says she has only eight unemployment days left out of ninety, and asks whether an offer letter this week would solve the problem.
        Situation ten. A candidate asks how much the offer letter costs, and whether paying for it means he is employed.
        Situation eleven. A requirement says No CPT or OPT, but the Account Manager asks you to submit a strong OPT candidate anyway because the client might not check.

        Questions to consider for each situation
        Is this question within a recruiter's role?
        What would you say to the candidate, using respectful and honest language?
        Who is the right person to answer: HR, payroll, compliance, the DSO, or a qualified professional?
        Do you need to escalate internally? To whom, and with what facts?
        What must you never say or do in this situation?

        Helpful phrases
        That is an important question, and I want you to get the correct answer. Your DSO is the right person to guide you.
        I cannot advise on that, but our HR team can explain our company's process.
        I am not able to represent the profile that way. I will discuss it with my lead.
        Let me make sure the right team reviews this, and I will update you.

        Reflection questions
        Which situations involved risk to the candidate? Which involved risk to the company?
        In which situation would staying silent be a problem?
        How can you remain helpful while staying within your role?

        Recruiter checklist
        Recognise boundary questions quickly.
        Refer to the right expert.
        Escalate improper requests.
        Never give legal advice or misrepresent status.

        Source note
        Situations nine, ten and eleven come from the company training material: the unemployment-day count in the Day 7 questionnaire, the offer letter step in the company's business process, and the work authorization checkpoint in the Day 5 training, which says never to alter or misrepresent a candidate's work authorization. The other situations are based on published government guidance and need review and approval by HR and the training manager.

        Key takeaway
        Knowing your boundaries is a professional strength. Refer, escalate and stay honest every time.
