        Reflection questions
        Did you make any assumptions while reading the resume? Which ones?
        How would you present her experience honestly in a submission?
        What would you do if she asked you to describe her manual testing role as automation?

        Recruiter checklist
        Match evidence, not keywords.
        Separate types of experience.
        Note gaps honestly.
        Prepare clear screening questions.

