        Learning objective
        Apply the job description analysis method from Levels 4 and 6 to a realistic requirement, and practise producing a clear requirement summary.

        How to use this scenario
        Read the scenario slowly. Then work through the practice steps on your own or with a colleague, before discussing your thinking with your trainer. There is no single perfect answer. The goal is to practise structured thinking.

        The scenario
        A vendor sends you this requirement at 9 a.m. Eastern Time on a Tuesday.
        Title: Data Engineer, mid level.
        Client: a large healthcare insurance company.
        Location: Austin, Texas, hybrid, two days a week in the office.
        Duration: nine months, W2, possible extension.
        Start: within three weeks.
        Summary: build and maintain data pipelines for claims data.
        Required: three or more years of experience with Python and SQL, experience with Spark, and experience with a cloud data platform.
        Preferred: Airflow, Snowflake, healthcare data experience.
        The requirement does not mention which work authorization types are accepted.
        The vendor asks for two strong profiles by Thursday.

        Practice steps
        Identify the must-have skills and the preferred skills.
        Identify the location, work mode, duration, start date and engagement type.
        List the questions you would ask the vendor before sourcing.
        Write a requirement summary in five or six short lines, as you would share it with your team.
        Write the primary and secondary keywords you would use in your search.
        Decide how you would prioritise this requirement against two other open requirements, and explain why.

        Points to think about
        What should you do about the missing work authorization information?
        How might the client count internship or academic experience toward three years?
        Does a start within three weeks suit candidates who are still waiting for their EAD?
        What does healthcare data experience mean for privacy expectations?

        Reflection questions
        Which part of the analysis took you the longest, and why?
        What would happen if you started sourcing without asking the vendor your questions?
        How would you explain this role in a sixty-second call?

        Recruiter checklist
        Separate must-haves from preferred skills.
        Clarify missing information with the vendor before sourcing.
        Write a clear, shareable summary.
        Plan keywords and priority.

        Key takeaway
        Good analysis turns a long job description into clear actions. Practise until it becomes a habit.
