        Learning objective
        Practise handling several common objections using the listen, acknowledge, clarify and respond method, with honesty and approved information.

        How to use this scenario
        Work in pairs. The person playing the candidate uses one objection at a time from the list below. The recruiter responds using the four-step method. After each objection, pause and review. Rotate through all objections and swap roles.

        The objections
        Objection one. I already work with another company, but I have been waiting for a project for six weeks.
        Objection two. How do I know your company is real? Are you E-Verified?
        Objection three. Why do you need my EAD before the interview? I do not feel comfortable sending it.
        Objection four. Another company told me they will guarantee my H-1B. Can you do the same?
        Objection five. Your rate is much lower than what my friend gets on C2C.
        Objection six. I do not want a contract role. I want a full-time job.
        Objection seven. I had a bad experience with a staffing company last year.

        The four-step method
        Listen fully.
        Acknowledge the concern.
        Clarify with a question.
        Respond with accurate, approved information, and check whether it helps.

        Company-specific process
        Your responses about E-Verify enrollment, sponsorship policy, benefits, rate structures and document requirements must use your company's approved wording. Verify with HR or authorized personnel. In practice, if you do not know the approved wording, practise saying that you will confirm with HR.

        Review questions after each objection
        Did the recruiter listen without interrupting?
        Did the recruiter acknowledge the concern sincerely?
        Did the clarifying question reveal the real concern?
        Was the response honest, with no promises or guarantees?
        Did the recruiter avoid criticising other companies?
        Did the recruiter respect the candidate's decision?

        Points to think about
        Which objection was hardest for you, and why?
        Where did you feel tempted to promise something?
        How did your tone change when the candidate sounded suspicious or annoyed?

        Recruiter checklist
        Use the four steps every time.
        Use approved company information.
        Never promise outcomes.
        Accept no gracefully.

        Key takeaway
        Practising objections in a safe setting prepares you to stay calm, honest and helpful on real calls.
