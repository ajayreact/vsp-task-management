        Learning objective
        Understand and verify a candidate's IT experience, including internships, academic projects and professional roles, and represent it honestly.

        What you need to know
        OPT candidates often have a mix of professional experience before their master's degree, internships during their studies, CPT work, and academic projects. Clients and vendors want to know how much real, relevant experience a candidate has. Your job is to understand it clearly and present it honestly.

        Types of experience to discuss
        Full-time professional roles, for example two years as a developer in India before the master's degree.
        Internships and CPT roles in the United States.
        Part-time or campus roles, such as research or teaching assistant roles involving technology.
        Academic projects and capstone projects.
        Freelance or open-source work.

        How to ask
        Could you walk me through your experience, starting with the most recent?
        For each role: What was the company or project? What were your responsibilities? What technologies did you use? How long were you there?
        Was this full-time, part-time, an internship or an academic project?

        Probing for depth
        What was the most challenging problem you solved in that role?
        What part of the system did you personally build?
        How large was the team?
        These questions show real experience and help you prepare the candidate for interviews.

        Counting experience honestly
        Count actual months of relevant work, not the whole duration of a degree.
        Ask the vendor how the client counts internships and academic projects.
        Never inflate experience in a submission or resume.
        Never advise a candidate to add experience they do not have. This is fraud and can have serious consequences for the candidate and your company.

        Gaps and changes
        Ask politely about gaps: I see a gap between June and December. Could you tell me about that time?
        Many gaps have simple explanations, such as study, travel or waiting for EAD. Record them honestly.

        Practical example
        A candidate's resume says three years of Java experience. During the call, you learn that she worked eighteen months as a Java developer in India, then did a six-month Java internship in the United States on CPT, and completed academic projects. You record two years of professional Java experience including the internship, plus academic projects. You ask the vendor whether this meets the three-year requirement.

        Recruiter checklist
        Ask about each role in detail.
        Distinguish professional, internship and academic work.
        Count months honestly.
        Never inflate or fabricate experience.

        Common mistakes
        Accepting the total years on the resume without checking.
        Presenting academic projects as professional experience.
        Coaching candidates to exaggerate.

        From the company calling script
        The Day 7 questionnaire asks for total U.S. IT experience, in years and months. Record U.S. experience separately from experience in other countries, because some clients ask specifically for U.S. experience, and the candidate's real history must be described accurately in any submission.
        Company-specific process: how internships, CPT roles and academic projects are presented in submissions follows the team's approved standard. Verify with HR or authorized personnel.

        Key takeaway
        Honest, well-understood experience is the foundation of a strong submission and a successful interview.
