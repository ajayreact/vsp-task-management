        Learning objective
        Ask about work authorization respectfully and consistently using approved questions, and record answers accurately.

        What you need to know
        Requirements often specify which work authorization types are accepted. Your company also has rules about which candidates it can employ. So you need accurate information about a candidate's work authorization. At the same time, there are legal and ethical limits on what you can ask and how. Use your company's approved questions, and ask every candidate in the same way.

        Approved style of questions
        Company-specific process: use your company's approved screening wording. Typical examples are:
        Are you currently authorized to work in the United States?
        Will you now or in the future require sponsorship for employment visa status?
        What type of work authorization do you have, and what are the start and end dates?
        Verify the exact approved questions with HR or authorized personnel before using them.

        What not to ask
        Questions about nationality, country of birth, religion, age, marital status or family plans.
        Questions that assume status from a name, accent or appearance.
        Requests for documents in the first call, unless your approved process requires it.

        Recording visa status
        Record the authorization type, such as OPT, STEM OPT, H-4 EAD or other.
        Record EAD dates exactly, with the month name.
        Record any pending application, such as a STEM OPT extension.
        Record what the candidate said, not your assumptions.

        Handling candidate questions about visas
        If a candidate asks whether their status allows a role, say: That is an important question. I will connect you with our HR team, and your DSO can also guide you.
        Never give legal opinions, and never guess.

        Unemployment awareness
        Company-specific process: OPT rules include limits on the number of days a candidate can be unemployed. Some companies ask candidates about this in screening, only through approved questions. Do not calculate or interpret unemployment days yourself. If a candidate is concerned, refer them to their DSO and your HR team. Verify with HR or authorized personnel.

        Practical example
        You ask your approved questions. The candidate says she is on OPT with an EAD valid from June 1 this year to May 31 next year, and plans to apply for STEM OPT. You record these facts exactly. She asks whether she should apply for STEM OPT soon. You say: Your DSO is the right person to guide you on timing. Our HR team can also explain our process.

        Recruiter checklist
        Use approved questions with every candidate.
        Record type and dates exactly.
        Never ask about protected characteristics.
        Refer legal and timing questions to HR and the DSO.

        Common mistakes
        Asking different questions to different candidates.
        Guessing status from profiles.
        Giving immigration advice.

        From the company calling script
        The OPT calling script asks, Let me know what is your visa status? and then, Expire date of visa? The Day 7 questionnaire records the status as F-1 CPT, F-1 initial OPT, F-1 STEM OPT, or other. It also asks how many unemployment days remain, out of ninety for initial OPT or one hundred and fifty in total with STEM OPT, and whether the current employer is E-Verified, which matters for STEM OPT.
        Ask for the expiry of the work authorization, meaning the EAD end date, rather than the visa stamp. An F-1 visa stamp in the passport can expire while the student's status remains valid.
        Company-specific process: use only the approved wording for status questions, and never decide eligibility yourself. Verify with HR or authorized personnel.

        Key takeaway
        Ask approved questions consistently, record facts accurately, and leave legal decisions to HR and compliance.
