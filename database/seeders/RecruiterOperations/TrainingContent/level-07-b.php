        Learning objective
        Confirm graduation and program end dates accurately, and understand how they relate to OPT timing at an awareness level.

        What you need to know
        Graduation timing affects when a candidate can start work. Many students apply for OPT before or around their program end date, and they cannot start working on OPT until their EAD start date. Candidates may also be confused between the graduation ceremony date, the program end date on their I-20 and the EAD start date.

