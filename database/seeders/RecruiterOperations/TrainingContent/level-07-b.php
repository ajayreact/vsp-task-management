        Learning objective
        Discuss a candidate's technical stack confidently, at a recruiter's level, to confirm the match with the requirement's must-have skills.

        What you need to know
        A technical stack is the set of technologies a person uses, such as programming languages, frameworks, databases, cloud platforms and tools. You do not need to be an engineer, but you must understand the main technologies in your requirements well enough to ask good questions and notice obvious mismatches.

        Common stack groups in OPT recruiting
        Java with Spring Boot, microservices and REST services.
        Python for development, data engineering or automation.
        Front-end with JavaScript, React or Angular.
        .NET with C sharp.
        Data with SQL, Python, Spark, Tableau or Power BI.
        Cloud with AWS, Azure or Google Cloud.
        QA with Selenium, Java or Python, and API testing tools.
        Business analysis with requirements, documentation and SQL.

        How to ask about the stack
        What are your primary skills, the ones you use most and are most confident in?
        Which of these did you use in real projects, and for how long?
        In the Spring Boot project, what did you build?
        Have you worked with Kafka or AWS? In what situation?
        Rate yourself from one to ten in Java, and tell me why.

        Recognising depth
        Strong answers include specific examples, versions, problems solved and results.
        Weak answers repeat general definitions or list tools without examples.
        Do not judge too quickly. Some candidates are nervous. Ask a follow-up question kindly.

        Matching to the requirement
        Compare the candidate's primary skills with the must-haves.
        Note which preferred skills they have.
        Be honest about gaps in your notes and submission.

        Preparing for technical interviews and assessments
        Tell the candidate which skills are most important for this client.
        Suggest reviewing core topics in those skills.
        Mention that the client may use a video technical interview or online assessment with the webcam on.
        Never help a candidate cheat in an assessment, and never allow anyone else to take an interview for a candidate. This is fraud and is grounds for immediate rejection and serious consequences.

        Practical example
        A candidate lists Java, Python, React, AWS, Kafka and Docker. When you ask about Kafka, he explains that he followed an online course but never used it in a project. You record Kafka as learning only. His Java and Spring Boot answers are detailed and confident. You submit him with an honest summary of strong Java and Spring Boot, and basic awareness of Kafka.

        Recruiter checklist
        Identify primary skills.
        Ask for project examples.
        Match must-haves honestly.
        Prepare candidates ethically.

        Common mistakes
        Accepting long skill lists at face value.
        Using technical words you do not understand.
        Ignoring signs of interview fraud.

        From the company calling script
