        Final semester end date.
        Program end date, as recorded by the school.
        Graduation ceremony date, which may be different.
        OPT application date.
        EAD start date and end date, once approved.
        Record each date separately and exactly.

        Why graduation timing matters for recruiting
        Candidates in their final semester are a pipeline for future requirements.
        Candidates who have graduated but are waiting for their EAD cannot start yet.
        Requirements with immediate starts need candidates who already have valid authorization.
        Always check these dates against the start date of the requirement, and confirm with HR when in doubt.

        Candidates still studying
        Students may be working on CPT during their studies. CPT authorization is managed by the school and is tied to the curriculum. Treat questions about CPT as you would OPT: record facts and refer details to HR and the DSO.

        Practical example
        A candidate says she graduated in May. You ask more questions and learn that her program end date was May 16, she applied for OPT in March, and her EAD start date is June 10. The requirement starts on June 3. You note that her authorization starts after the requirement start date and ask the vendor whether a June 10 start is possible.

        Recruiter checklist
        Ask for the program end date, not just graduation.
        Record all key dates separately.
        Compare dates with the requirement start date.
        Refer CPT and OPT questions to HR and the DSO.

        Common mistakes
        Assuming graduation means the candidate can start work.
        Mixing up the ceremony date and program end date.
        Not asking about the OPT application status.

        From the company calling script
        The OPT calling script asks, When did you finish masters? The Day 7 questionnaire records the graduation date as month and year. Write it in that format every time, for example May 2025, so that teammates and HR read it the same way.
        Company-specific process: HR, not the recruiter, compares graduation, OPT and EAD dates when a question about eligibility arises. Verify with HR or authorized personnel.

        Key takeaway
        Graduation is not the same as work authorization. Record each date separately and compare them with the start date.
