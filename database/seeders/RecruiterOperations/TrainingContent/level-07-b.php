        Learning objective
        Discuss relocation openly and realistically with candidates, and record their relocation preferences accurately.

        What you need to know
        Many OPT candidates are flexible about location, because they are starting their careers. Others have strong reasons to stay where they are, such as family, a partner's job or a lease. Clients with onsite or hybrid roles need candidates who will genuinely relocate in time. A candidate who agrees to relocate on a call but changes their mind after selection causes serious problems for everyone.

        How to ask about relocation
        This role is in Charlotte, North Carolina, hybrid three days a week. Would you be open to relocating to Charlotte?
        If you were selected, how soon could you relocate?
        Are there any locations you would not consider?
        Is there anything that might make relocation difficult for you?

        Making relocation realistic
        Ask about timing: Could you be in Charlotte by the start date?
        Ask about practical matters: Do you have a plan for housing?
        Explain the work mode clearly: The client expects three days in the office every week, not occasional visits.
        Company-specific process: whether your company offers any relocation support is a company decision. Do not mention relocation assistance unless it is approved. Verify with HR or authorized personnel.

        Recording relocation preferences
        Open to relocating anywhere in the United States.
        Open to specific states or cities.
        Open to relocating only for certain roles or rates.
        Not open to relocating.
        Also record the earliest relocation date.

        Relocation in submissions
        State clearly that the candidate is relocating, from where and by when. Never present a relocating candidate as already local.

        Relocation and payroll awareness
        When a consultant relocates, their home and work states may change. HR and payroll must know the dates in advance, because state taxes and unemployment insurance may change. Record the planned move and include it in your handoff.

        Practical example
        A candidate in New Jersey says she is open to relocation. You ask more questions and learn that her spouse works in New Jersey and that she prefers roles within driving distance. You record: open to relocating within the Northeast only. You do not submit her for the Charlotte role, but you note her for future roles in New York and Pennsylvania.

        Recruiter checklist
        Ask specific relocation questions.
        Check timing and practical readiness.
        Record preferences and dates accurately.
        Do not promise relocation support without approval.

        Common mistakes
        Accepting yes, I can relocate without follow-up questions.
        Hiding the work mode until after selection.
        Forgetting to inform payroll about moves.

        From the company calling script
        The OPT calling script asks two relocation questions: Re-location? and, Are you open for relocation for training and projects? It later explains that candidates must be open to relocating for the training and placement program. The Day 7 questionnaire records relocation status as one of three options: fully open, remote only, or local only.
        Company-specific process: if relocation for training is part of the program, the location, accommodation and any costs must be confirmed in writing before you discuss them. Verify with HR or authorized personnel.

        Key takeaway
        Relocation must be genuine and realistic. Ask specific questions, record honestly, and share planned moves with HR and payroll.
