        Important note
        This lesson is for recruiter awareness only. It is not legal advice. Immigration rules can change, so verify current requirements on official sources and follow company and HR processes.

        Learning objective
        Understand Optional Practical Training, the core work authorization behind most OPT recruiting, and the key dates recruiters must track.

        What you need to know
        Optional Practical Training, known as OPT, is temporary employment authorization for F-1 students. It allows practical work experience directly related to the student's major field of study.
        Under current rules, a student can generally receive up to twelve months of OPT per higher degree level.
        OPT can be pre-completion, used before the program ends, or post-completion, used after the program ends. Most of your candidates use post-completion OPT.

        How a student gets OPT
        The DSO recommends OPT in SEVIS and issues an updated I-20.
        The student files Form I-765 with U.S. Citizenship and Immigration Services.
        If approved, the student receives an Employment Authorization Document, the EAD card.
        The student may begin work only on or after the start date on the EAD card, and only once they have the approved card.

        Key dates recruiters track
        Program end date, from the I-20.
        EAD start date and end date, from the EAD card.
        Employment start date with the new employer.

        Unemployment awareness
        During post-completion OPT, students are generally allowed a limited number of days of unemployment, currently commonly cited as ninety days. Time without qualifying employment counts toward this limit. Candidates should track this with their DSO. Recruiters should be aware of it, because a candidate close to the limit may be under pressure, but recruiters must never advise on it.

        Reporting
        Students on OPT must report employment details, such as employer name and address, to their school or the SEVP portal within required time frames. This is the candidate's responsibility, guided by the DSO.

        From the company training material
        The OPT Recruiter Training Material teaches that OPT is given to F-1 students after they complete their bachelor's or master's degree in the U.S., and that they are eligible to work legally anywhere in the U.S. It states that OPT validity is twelve months and can be extended by up to twenty-four months, for a total of thirty-six months, and that MBA students have OPT for twelve months only.
        Read those points precisely. The twenty-four month extension is STEM OPT, and only graduates of qualifying STEM degree programs can apply for it. So thirty-six months is the maximum for a STEM graduate, not the normal case. Most MBA programs are not STEM programs, which is why the handout says twelve months, but some MBA programs are STEM designated. Do not assume either way. And OPT work anywhere in the U.S. must still relate to the student's field of study.

        Job relevance
        The job must be directly related to the student's degree. A computer science graduate in a software role is a clear example. If you are unsure whether a role relates to a candidate's degree, do not decide yourself. Escalate according to company policy.

        Practical example
        A candidate shares that her EAD is valid from June 1 to May 31 next year. She graduated in December. You record both dates, note that she can start work from June 1, and inform your HR team that her EAD end date is next May so that they can plan for STEM OPT if she is eligible.

        Recruiter checklist
        Record EAD start and end dates accurately.
        Never suggest that a candidate can start before the EAD start date.
        Ask about the candidate's degree and major.
        Escalate job-relevance questions instead of deciding yourself.

        Common mistakes
        Assuming an approved application means the candidate can start immediately.
        Calculating unemployment days for the candidate.
        Ignoring the EAD end date during placement.

        Key takeaway
        OPT is the foundation of your work. Track the dates carefully, respect the rules, and refer status questions to the DSO and HR.
