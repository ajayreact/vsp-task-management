        'Opportunity Explanation' => <<<'TEXT'
        Learning objective
        Explain a job opportunity clearly and completely, so that the candidate can make an informed decision about moving forward.

        What you need to know
        After the introduction, candidates want to understand the role. A good opportunity explanation is organised, accurate and honest. It covers what the candidate will do, where, for how long, and under what terms, without confidential details that the vendor has not allowed you to share.

        What to explain
        Job title and level.
        Client industry, and the client name only if you are allowed to share it.
        Key responsibilities, in simple words.
        Required skills, and preferred skills.
        Location and work mode: onsite, hybrid or remote, with days in office.
        Duration and engagement type, such as a twelve-month W2 contract.
        Start date.
        Interview process, if known.
        Pay rate or salary range, when appropriate and approved.

        A simple order to follow
        Start with the big picture: role, industry, location.
        Then explain the work: responsibilities and skills.
        Then the terms: duration, type, start date and pay.
        Then the process: what happens next.

        Sample explanation
        This is a Java developer role with a large banking client. You would be building and maintaining REST services using Java and Spring Boot, and working with SQL databases. Kafka and AWS experience would be a plus. The role is in Charlotte, North Carolina, hybrid with three days in the office. It is a twelve-month W2 contract with a possible extension, starting in about two weeks. The interview process is usually a technical video call followed by a manager discussion.

        Being honest about uncertainty
        If extension is possible but not guaranteed, say so.
        If the interview process is unknown, say you will confirm it.
        If the client name is confidential, explain that it will be shared later.

        Checking understanding
        Ask: Does this sound like the kind of role you are looking for?
        Ask: Do you have any questions about the responsibilities or the location?
        Listen to the answers. They reveal the candidate's real interest and concerns.

        Practical example
        A candidate asks whether the role is fully remote. You explain clearly: It is hybrid, three days a week in the Charlotte office. The client has been firm about this. He says he cannot relocate. You thank him, note his preference for remote roles, and promise to contact him for suitable future roles.

        Recruiter checklist
        Explain role, work, terms and process in order.
        Use simple words.
        Be honest about what is uncertain.
        Check the candidate's understanding and interest.

        Common mistakes
        Reading the job description word by word.
        Hiding the work mode or location until later.
        Describing a possible extension as guaranteed.

        From the company calling script: the training and placement program
        In the OPT calling script, after asking about technology, the recruiter explains the program. In plain words, the script says this.
        We have multiple openings in IT development with our direct clients all over the U.S. You need to be open to relocation for the training and placement program. At our headquarters, you will get in-class training. We will give you an offer letter if you relocate to our head office. We will provide accommodation at the headquarters. The training period is about four to five weeks. Soon after training, we will prepare your resume and place you with our direct clients.
        If the candidate asks, why VSP Group, the script lists: in-class training, a large marketing team with dedicated account managers, direct clients all over the U.S., internal staff of more than one hundred people, and H-1B and Green Card sponsorship.

        How to explain this honestly
        Describe each part as a process, not a promise. Training is offered. Marketing and placement are the goal, but no placement or start date is guaranteed. Sponsorship is decided case by case under company policy and government rules, and an H-1B selection is never guaranteed. An offer letter is issued by HR for a genuine position, not as a reward for relocating.
        Company-specific process: the training location, duration, accommodation, offer letter terms, any cost to the candidate and the sponsorship policy must all be confirmed in writing before you describe them. Verify with HR or authorized personnel. For OPT candidates, HR and compliance decide how training and employment fit the candidate's work authorization.

        Key takeaway
        A clear and honest explanation helps candidates decide quickly and prevents problems later in the process.
