        Practical example
        You complete a twenty-minute screening. The candidate is in Atlanta, will relocate to Charlotte, has a master's in computer science graduating in May, two years and ten months of Java experience including internships, an approved OPT with EAD starting June 1, and a rate expectation within range. She has a webcam and a quiet place for interviews. You summarise, confirm interest and agree on next steps.

        Recruiter checklist
        Follow the call structure.
        Use smooth transitions.
        Cover every topic, including webcam readiness.
        Close with a summary and a next step.

        Common mistakes
        Jumping between topics randomly.
        Forgetting important topics such as availability.
        Ending without a clear next step.

        From the company calling script: the Day 7 screening questionnaire
        The Calling script and Practice document gives a questionnaire that trainers teach recruiters to copy into the applicant tracking system during every initial screening call. It has four parts.
