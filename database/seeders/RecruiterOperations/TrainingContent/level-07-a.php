        'Recruiter Introduction' => <<<'TEXT'
        Learning objective
        Introduce yourself confidently and professionally at the start of every call, so that the candidate knows who you are, why you are calling and that you respect their time.

        What you need to know
        The first fifteen seconds of a call decide whether the candidate keeps listening. Many OPT candidates receive several recruiter calls every day, and some have had bad experiences with unclear or unprofessional callers. A clear, calm and friendly introduction immediately separates you from the rest.

        The four parts of a recruiter introduction
        Greeting. Use the candidate's name, pronounced carefully. If you are unsure of the pronunciation, ask politely later in the call.
        Your name and company. Say your full first name and your company's name clearly and slowly.
        The reason for your call. Mention a specific role or the fact that you saw their profile.
        Permission. Ask whether this is a good time to talk.

        Sample introduction
        Hello, am I speaking with Rahul? Hi Rahul, this is Anita calling from our company. I am a recruiter, and I came across your profile for a Java developer opportunity. Is this a good time to talk for about five minutes?

        Voice and pace
        Speak slightly slower than you normally would, especially on international or mobile lines.
        Smile while you speak. Candidates can hear warmth in your voice.
        Use a calm, confident tone. Avoid sounding rushed or scripted.
        Pause after asking for permission and let the candidate answer.

        Indian English on U.S. calls
        Many OPT candidates are themselves from India or other countries, and many vendors and clients are in the United States. Clear pronunciation matters more than accent. Speak each word clearly, avoid very fast speech, and avoid local expressions that may confuse listeners, such as do the needful or revert back. Say please let me know, or I will get back to you, instead.

        When it is not a good time
        Respect the answer immediately. Ask: When would be a better time to call you? Confirm the time and the time zone, and call exactly then. A rescheduled call that happens on time builds trust.

        Your calling environment
        Use a quiet place with a good headset.
        Keep the requirement and your notes in front of you.
        Close distractions, such as chat windows and loud backgrounds.
        Check the candidate's time zone before calling.

        Practical example
        You call a candidate at 10 a.m. Eastern Time. She answers in a busy place. You introduce yourself, mention the role, and ask whether it is a good time. She says she is commuting. You reply: No problem at all. Would 1 p.m. Eastern today work for you? She agrees. You send a short text confirming the time, with your name and company, and call at exactly 1 p.m.

        Recruiter checklist
        Greet by name.
        State your name and company clearly.
        Give a specific reason for calling.
        Ask permission and respect the answer.
        Prepare your environment before calling.

        Common mistakes
        Starting to pitch before introducing yourself.
        Speaking too fast or mumbling the company name.
        Continuing when the candidate says it is a bad time.
        Calling at an inconvenient hour in the candidate's time zone.

        From the company calling script
        The OPT Recruiter Training Material gives the company's standard opening, under the heading How to speak with a consultant.
        Recruiter: Greetings of the day! Hi, this is Kiran calling from VSP Group. Am I speaking to the candidate's name?
        Recruiter: How are you doing?
        Recruiter: This call is regarding a job opportunity for you. Is this the right time to speak with you?
