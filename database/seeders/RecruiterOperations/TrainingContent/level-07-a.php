        'Current Location' => <<<'TEXT'
        Learning objective
        Ask about and record a candidate's current location accurately, and understand why location affects submissions, interviews and payroll.

        What you need to know
        Location affects almost every part of recruiting. Clients care about whether a candidate can work onsite or hybrid. Vendors often ask for the candidate's current city and state. Payroll needs to know where the consultant will physically work. Interview scheduling depends on the time zone. So you need an accurate answer, not an assumption from a profile.

        How to ask
        Where are you currently located? Which city and state?
        Are you planning to stay there, or might you move soon?
        If they are a student: Are you near your university, or somewhere else?

        What to record
        City and state, spelled correctly.
        Time zone.
        Whether this location is temporary, such as staying with friends after graduation.
        Any planned move date.

        Why profiles can be wrong
        LinkedIn profiles often show the university's location or an old internship location. Resumes may be outdated. Always confirm verbally.

        Location and submissions
        Vendors and clients may prefer local candidates for onsite and hybrid roles.
        Never misrepresent a candidate's location to make them look local. If the candidate will relocate, state that clearly in the submission, with the planned date.

        Location and time zones
        Schedule calls and interviews in the candidate's time zone.
        Confirm time zones in writing, for example 10 a.m. Central Time.

        Location and payroll awareness
        The state where a consultant works can affect state taxes and unemployment insurance. If a candidate will work remotely from a different state, payroll and HR must know. You do not need to know the tax details. You just need to record and hand off the facts accurately.

        Practical example
        A candidate's LinkedIn profile says Boston, but during the call she says she moved to Dallas last month to stay with relatives. You record Dallas, Texas, Central Time, temporary, and that she is open to relocating anywhere in Texas. You submit her as located in Dallas.

        Recruiter checklist
        Confirm the city and state verbally.
        Record the time zone.
        Note temporary locations and planned moves.
        Never misrepresent location.

        Common mistakes
        Copying location from the profile without asking.
        Saying a candidate is local when they are not.
        Forgetting to update the record when the candidate moves.

        From the company calling script
        The OPT calling script asks simply, Location? The Day 7 questionnaire is more precise: current location, city and state. Always record both the city and the state, because many U.S. cities share names. For example, there is a Portland in Oregon and another in Maine.

        Key takeaway
        Accurate location information supports honest submissions, correct scheduling and accurate payroll.
