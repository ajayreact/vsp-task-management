        Learning objective
        Present yourself as a professional, trustworthy recruiter in calls, messages and emails, with consistent identity and behaviour.

        What you need to know
        The recruiter introduction gets you started. A professional introduction goes further: it shows the candidate that you are a real person, from a real company, with a clear role and a professional way of working. This is important because candidates are cautious about fraud and fake recruiters, especially in the OPT market.

        Elements of a professional identity
        Your real name, used consistently in calls, email and LinkedIn.
        Your title, such as OPT Recruiter or Senior OPT Recruiter.
        Your official company email address and signature.
        A complete LinkedIn profile with your photo, title and company.
        Your company's official website and contact number, if your company shares them.

        A professional introduction in a call
        After the greeting, you might say: I work as an OPT recruiter with our company. We are an IT staffing company, and we work with vendors and clients across the United States to place consultants on IT projects. I focus on candidates who are on OPT and STEM OPT.
        Use only the approved description of your company. Company-specific process: the exact wording about your company's business, locations and history must come from management. Verify with HR or authorized personnel before using any new description.

        A professional introduction by email
        Subject line: Java Developer opportunity in Charlotte, North Carolina.
        Opening: Dear Rahul, my name is Anita, and I am an OPT recruiter with our company.
        Purpose: one or two lines about the role.
        Call to action: Would you be available for a short call tomorrow?
        Signature: name, title, company, official email and phone number.

        Professional behaviour
        Be on time for every scheduled call.
        Keep your promises, such as sending a job description.
        Use a polite tone even when a candidate is rude or uninterested.
        Never ask for sensitive documents in the first conversation.
        Never ask for money.

        Practical example
        A candidate asks: How do I know you are a real recruiter? You reply: That is a very fair question. My name is Anita, and you can see my profile on LinkedIn with our company name. I will send you an email from my official company address after this call, and you can check our company website. Then you follow through.

        Recruiter checklist
        Use your real name and title consistently.
        Use official email and a complete signature.
        Describe your company only with approved wording.
        Keep every promise you make in the call.

        Common mistakes
        Using personal email addresses for recruiting.
        Using different names on different platforms.
        Describing the company in exaggerated terms.
        Requesting documents too early.

