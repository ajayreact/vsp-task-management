        Webcam and technical assessments
        Many clients now hold interviews and technical assessments over video. Ask whether the candidate has a working webcam, a stable internet connection and a quiet place for video interviews. Explain that some clients may ask for coding or technical assessments with the camera on. Company-specific process: if your company runs its own technical or webcam assessment before submission, explain it using approved wording. Verify with HR or authorized personnel.

