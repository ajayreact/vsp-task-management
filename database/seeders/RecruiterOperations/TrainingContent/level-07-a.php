        '60-Second Cold Call' => <<<'TEXT'
        Learning objective
        Deliver a clear, natural sixty-second cold call that introduces you, the opportunity and the next step, and invites the candidate to talk.

        What you need to know
        A cold call is a call to a candidate who is not expecting you. Most candidates decide within a minute whether to continue. A good sixty-second call is short, specific and honest. It is not a speech. It is an invitation to a conversation.

        Structure of the sixty-second call
        Seconds 0 to 10. Greeting, your name and company, and permission.
        Seconds 10 to 30. Why you are calling: the role, the location and one interesting detail.
        Seconds 30 to 45. Why them: one detail from their profile that matches.
        Seconds 45 to 60. A question that invites them to talk.

        Sample sixty-second call
        Hello, is this Rahul? Hi Rahul, this is Anita from our company. I am an OPT recruiter. Do you have a minute?
        Thank you. I am working on a Java developer role with a banking client in Charlotte, North Carolina. It is a twelve-month W2 contract, hybrid three days a week.
        I saw on your profile that you worked with Spring Boot and REST APIs during your internship, which matches what the client needs.
        Are you currently exploring new opportunities?

        After the sixty seconds
        If the candidate is interested, move to the initial screening, or schedule it.
        If they are not interested now, ask whether you can stay in touch for future roles, and what type of roles they prefer.
        If they are already placed, congratulate them and ask whether they know anyone who might be interested.

        Delivering it naturally
        Practise until it sounds like a conversation, not a script.
        Change the details for every requirement and every candidate.
        Pause after questions.
        Listen carefully to the first answer. It tells you how to continue.

        What to avoid in a cold call
        Long company history.
        Pressure, such as you must decide today.
        Claims you cannot support, such as best rates in the market.
        Asking for documents or personal details.
        Promising interviews, offers or sponsorship.

        Practical example
        You call a candidate who answers quickly and sounds busy. You keep it to forty seconds: name, role, location, one match, and the question. He says he is interested, but busy right now. You schedule a screening call for that evening in his time zone and send a short confirmation message.

        Recruiter checklist
        Prepare the role summary and one personal match.
        Keep it under one minute.
        End with a question.
        Agree on a clear next step.

        Common mistakes
        Talking for three minutes without a pause.
        Using the same generic pitch for everyone.
        Forgetting the next step.

        From the company calling script: the Day 6 sixty-second cold call
        The Calling script and Practice document gives this script for calling an F-1 student or graduate about a bench-marketing or direct-placement opportunity.
        Recruiter: Hi, candidate's name, my name is your name from company name. I was reviewing your profile on LinkedIn or Dice and was really impressed by your technical background in, for example, data engineering or Java development. I know your time is valuable, so I will keep this brief. Do you have sixty seconds to talk about an active project opportunity?
        Candidate: Sure. What is it about?
        Recruiter: Great. We specialise in placing talented F-1 international graduates with clients across the U.S. Right now, we are building a developer pipeline for an upcoming project that fits your stack in, mention one or two core skills from their resume. I wanted to see if you are currently open to new opportunities.
        Candidate: Yes, I am on OPT right now and looking.
        Recruiter: Perfect. I would like to walk you through our placement process and check your timelines. Do you have five minutes right now to go over the details, or should I send a calendar invite for later today?
        Notice the structure: name and source of the profile, a specific compliment, permission for sixty seconds, one sentence about the opportunity, one question, and a choice of next step.

        What to change from the original script
        The original script also says the company is completely E-Verified and has a dedicated legal team that handles STEM OPT extensions and H-1B sponsorships without any hiccups, and describes the clients as tier-1. Do not say these lines as written. No employer can promise that STEM OPT or H-1B filings will succeed, and an opening call is not the place for immigration claims. If the candidate asks about E-Verify or sponsorship, give only the facts approved by HR, for example: Yes, our company participates in E-Verify, and HR can share the details.
        Company-specific process: E-Verify participation, client descriptions and sponsorship policy must be confirmed before you mention them. Verify with HR or authorized personnel.

        Key takeaway
        A great cold call is short, specific and honest, and it always ends with a question and a next step.
