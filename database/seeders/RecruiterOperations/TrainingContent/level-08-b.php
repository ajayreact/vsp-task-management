        'Phone Outreach' => <<<'TEXT'
        Learning objective
        Use phone outreach effectively and respectfully, including timing, voicemail and text follow-up.

        What you need to know
        A phone call is often the fastest way to start a real conversation. Many candidates are more likely to respond to a short, clear call than to an email. However, candidates receive many calls and may not answer unknown numbers. Phone outreach needs good timing, clear voicemails and respectful follow-up.

        Before calling
        Confirm that the candidate has shared the number or agreed to calls.
        Check the candidate's time zone.
        Prepare your sixty-second call and the role summary.
        Check your company records for previous contact.

        Best times to call
        Mid-morning and early afternoon in the candidate's time zone.
        Avoid early morning, late evening and meal times.
        For students, avoid typical class times if you know them.

        Leaving a voicemail
        Keep it under thirty seconds.
        Say your name, company and the reason for calling.
        Say your number slowly, twice.
        Example: Hello Rahul, this is Anita from our company. I am calling about a Java developer role in Charlotte that matches your Spring Boot experience. Please call me back at your convenience. My number is, and then the number, repeated twice. Thank you.

        Text follow-up
        If the candidate agreed to texts, send a short message after the voicemail: Hello Rahul, this is Anita from our company. I just left you a voicemail about a Java role in Charlotte. Please let me know a good time to talk.
        Do not send long details or documents by text.

        Respecting candidate choices
        Call no more than two or three times without a reply.
        Stop calling if the candidate asks.
        Record call attempts and outcomes.

        Practical example
        You call a candidate at 11 a.m. Central Time. There is no answer. You leave a short voicemail and send a short text, because she agreed to texts on her application. She texts back an hour later asking for a call at 3 p.m. You call exactly at 3 p.m.

        Recruiter checklist
        Call at reasonable times in the candidate's time zone.
        Leave short, clear voicemails.
        Follow up by text only if agreed.
        Limit attempts and respect requests.

        Common mistakes
        Calling repeatedly in one day.
        Leaving long, unclear voicemails.
        Calling at unreasonable hours.

        Key takeaway
        Respectful timing, clear voicemails and limited attempts make phone outreach effective and professional.
