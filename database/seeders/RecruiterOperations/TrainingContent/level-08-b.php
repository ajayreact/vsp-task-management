        Recruiter checklist
        Plan referral requests at good moments.
        Be specific and make sharing easy.
        Follow official referral programs only.
        Treat referred candidates fairly and promptly.

        Common mistakes
        Asking only once and never again.
        Promising unofficial rewards.
        Forgetting to thank referrers.

        Key takeaway
        Planned referral outreach turns good relationships into a steady flow of trusted candidates.
