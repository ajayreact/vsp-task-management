        Learning objective
        Time outreach activities to match academic calendars, U.S. business hours and candidate situations, for better responses.

        What you need to know
        The same message can get very different results depending on when it is sent. In OPT recruiting, timing depends on three calendars: the U.S. business day, the academic calendar, and the candidate's personal authorization timeline. Because many recruiters work from India, time zone planning is also essential.

        U.S. business day timing
        Send messages and make calls in the candidate's mid-morning or early afternoon.
        Remember that the United States has several time zones, from Eastern to Pacific.
        Avoid weekends and U.S. federal holidays unless the candidate prefers them.
        From India, the U.S. Eastern morning is usually Indian evening, depending on daylight saving time.

        Academic calendar timing
        Final semester: students start searching for roles. Build relationships early.
        Exam periods: students are busy. Reduce outreach.
        Graduation months, usually May and December: high activity, many new OPT applicants.
        Summer: some students are on internships or CPT.
        New semester start: career centers plan events. Good time to contact them.

        Candidate timeline timing
        Candidates waiting for EAD approval: maintain contact, and plan for the expected start.
        Candidates with active EAD and no job: high urgency. Respond quickly.
        Candidates near the end of a project: contact a few weeks before the end.
        Candidates approaching an authorization end date: inform HR and your lead, according to company process.

        Requirement timing
        Urgent requirements need fast outreach to your existing pipeline first.
        Future requirements allow planned outreach.

        Practical example
        You plan outreach for junior roles expected to open in June. In April, you contact final-semester students at three universities through approved channels. In May, during exams, you reduce outreach. Right after graduation, you contact interested students again. When the roles open, you have a ready pipeline.

        Recruiter checklist
        Plan around U.S. business hours and time zones.
        Plan around the academic calendar.
        Consider each candidate's authorization timeline.
        Prioritise urgent requirements with your existing pipeline.

        Common mistakes
        Sending outreach in the middle of the night in the candidate's time zone.
        Heavy outreach during exam weeks.
        Ignoring graduation seasons.

        Key takeaway
        Good timing multiplies the effect of good messages. Plan around clocks, calendars and candidate situations.
