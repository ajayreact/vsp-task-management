        'Email Outreach' => <<<'TEXT'
        Learning objective
        Use email outreach professionally to reach candidates, with clear content, correct timing and respect for privacy.

        What you need to know
        Email outreach is useful when candidates have shared their email, applied for a role, or joined your company's approved database. Email allows you to share more detail than a short message, such as a job description. Because email is easy to ignore or mark as spam, it must be relevant and well written.

        When to use email outreach
        Candidates who applied through job boards or career portals.
        Candidates in your company's database who agreed to be contacted.
        Candidates who asked you to email them after a call or message.

        Writing an outreach email
        Subject line: specific and short, such as Junior QA Automation role, Atlanta, hybrid.
        Opening: name, your role and company.
        Reason: why this role fits their profile.
        Details: key responsibilities, skills, location, work mode, duration and engagement type.
        Request: a short call, with suggested times and time zone.
        Signature: name, title, company, official email and phone.

        Sample outreach email
        Subject: Junior QA Automation role, Atlanta, hybrid.
        Dear Meera, I am Anita, an OPT recruiter with our company. I noticed that you applied for QA roles on our career page, and your Selenium and Java projects match a junior QA automation role with a retail client in Atlanta, hybrid three days a week, on a twelve-month W2 contract. Would you be available for a fifteen-minute call on Tuesday or Wednesday between 10 a.m. and 2 p.m. Eastern Time? Best regards, Anita.

        Timing
        Send emails during the candidate's business morning.
        Avoid weekends unless the candidate prefers them.
        Follow up after three to five business days.

        Privacy and compliance
        Email only candidates who have shared their address or agreed to contact.
        Never put multiple candidates in the same visible recipient list.
        Include a way to opt out of further emails, following company policy.
        Do not request sensitive documents in outreach emails.

        Practical example
        You email ten candidates who applied for QA roles in the last month, each with a personalised first line. Six reply, and four schedule calls. One asks to stop receiving emails. You record the request and stop contacting him.

        Recruiter checklist
        Email only candidates who agreed to contact.
        Write specific subject lines and clear details.
        Send at the right time.
        Respect opt-out requests.

        Common mistakes
        Sending mass emails with all recipients visible.
        Vague subject lines.
        Ignoring opt-out requests.

        Key takeaway
        Relevant, well-timed and privacy-respecting emails turn applications into conversations.
