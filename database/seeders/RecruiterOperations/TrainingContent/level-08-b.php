        Build long-term professional relationships with candidates, consultants, universities and partners that support consistent recruiting success.

        What you need to know
        Recruiting is a relationship business. A candidate you speak with today may be placed next year, refer five friends, or become a team lead who sends you requirements. Universities and organisations that trust you will continue to work with you. Relationships are built slowly through many small, consistent actions.

