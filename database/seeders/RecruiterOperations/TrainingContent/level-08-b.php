        Contact them within one business day.
        Mention the referrer only if the referrer agreed.
        Follow the same screening and consent process as every candidate.
        Keep the referrer updated in general terms.

        Thanking referrers
        Thank them every time, even when the referral is not placed.
        Follow the official process for any approved reward.

