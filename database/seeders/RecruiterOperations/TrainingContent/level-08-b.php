        Check in regularly after placement.
        Help them connect with the right team for questions.
        Ask about their career goals and future plans.

        Building relationships with universities and organisations
        Follow their rules and keep your promises.
        Thank them for support.
        Offer helpful contributions, such as interview tips sessions, when approved.

        Protecting relationships
        Never share private information.
        Never make promises you cannot keep.
        Apologise and correct mistakes quickly.
        End relationships professionally if needed.

