        A candidate you screened a year ago was not placed because her EAD was delayed. You kept in touch every few months, shared interview tips, and congratulated her on her approval. When a matching role opened, she contacted you first and was placed. Later, she referred two friends.

        Recruiter checklist
        Be honest, reliable and respectful.
        Keep in touch beyond active roles.
        Record important details.
        Protect privacy and keep promises.

        Common mistakes
        Contacting people only when you need something.
        Forgetting details people shared.
        Breaking small promises.

        Key takeaway
        Long-term relationships are built through honesty, reliability and respect, one interaction at a time.
