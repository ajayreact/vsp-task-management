        Learning objective
        Reach out to individual OPT candidates in a way that is personal, relevant, honest and respectful of their choices.

        What you need to know
        Candidate outreach is the first contact with a potential candidate, through LinkedIn, email, phone or other approved channels. Candidates decide quickly whether to respond. They respond to messages that feel personal and relevant, from recruiters who look professional and trustworthy.

        Before reaching out
        Review the candidate's profile or resume.
        Check that the role matches their skills and location preferences.
        Check whether the requirement accepts OPT and STEM OPT candidates.
        Check your company records to see whether a colleague is already in contact with the candidate.

        Elements of a good outreach message
        Personal greeting, using the candidate's name.
        Your name, role and company.
        A specific reason, such as their skills or project.
        Short role summary with location and work mode.
        A simple request, such as a short call.

        Choosing the channel
        LinkedIn for candidates found on LinkedIn.
        Email for candidates who applied or shared their email.
        Phone for candidates who shared their number and agreed to calls.
        Use the channel the candidate has chosen, and respect requests to change it.

        Respecting candidate choices
        If a candidate says no, thank them and respect it.
        If a candidate asks not to be contacted, record it and stop contacting them.
        Do not contact candidates at unreasonable hours in their time zone.

        Avoiding misleading outreach
        Do not exaggerate the role or the rate.
        Do not suggest sponsorship or guarantees.
        Do not imply the candidate has been selected.

        Practical example
        You find a recent graduate with Python, SQL and Tableau skills, and a capstone project on retail sales forecasting. You send a short message mentioning her project, introducing a data analyst role in Dallas, hybrid two days a week, and asking whether she would be open to a call. She replies the same day.

        Recruiter checklist
        Research before reaching out.
        Personalise every message.
        Use the candidate's preferred channel.
        Respect every decision.

        Common mistakes
        Contacting candidates for unsuitable roles.
        Contacting candidates a colleague already manages.
        Ignoring requests to stop contact.

        Key takeaway
        Personal, relevant and respectful outreach earns candidate attention and trust.
