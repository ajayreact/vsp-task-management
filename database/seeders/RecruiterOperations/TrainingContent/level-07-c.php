        Learning objective
        Confirm a candidate's availability for interviews and for starting work, and record it in a way that supports realistic planning.

        What you need to know
        Availability has two parts. Interview availability is when the candidate can attend calls and interviews. Start availability is the earliest date the candidate can begin work, considering authorization dates, notice periods, relocation and personal commitments. Vendors always ask for both.

        How to ask about interview availability
        What days and times are best for interviews this week and next week?
        Which time zone should I use?
