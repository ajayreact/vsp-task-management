        'Rate Discussion' => <<<'TEXT'
        Learning objective
        Discuss pay rates professionally and transparently within approved limits, and handle rate questions without making promises.

        What you need to know
        Rate is one of the most sensitive topics in recruiting. Candidates want fair pay. Your company has approved pay ranges based on the client bill rate, costs and margins. Your job is to discuss pay honestly, within the approved range, and to record the agreed rate accurately.

        Before discussing rate
        Know the approved pay range for the requirement.
        Know whether the rate is hourly or annual, and whether it is W2.
        Know what is included, such as benefits, if applicable.
        Company-specific process: rate ranges, any split or margin arrangements, and benefits are decided by management. Do not discuss internal margins or bill rates with candidates. Verify with HR or authorized personnel.

        How to ask about expectations
        What are your expectations for an hourly rate on W2?
        What range would you be comfortable with for this role and location?
        Are your expectations flexible for the right role?

        Sharing the approved rate
        The approved rate for this role is in the range of a certain amount per hour on W2.
        Be clear about what is approved. Do not suggest a higher rate is possible unless your lead has agreed.

        Understanding rate and split questions
        Some candidates ask about rate splits, such as a percentage of the bill rate. Company-specific process: how your company structures pay is a company policy. Share only the approved explanation, or refer the candidate to your lead. Never invent a split or promise a percentage.

        When expectations do not match
        Listen to the reasons, such as cost of living in the work location.
        Share the approved range honestly.
        If appropriate, ask your lead whether any flexibility exists.
        If there is no match, thank the candidate and keep them for suitable future roles.

        Recording the rate
        Record the agreed rate, type, and the date it was agreed.
        Include it in the interest confirmation and the RTR.
        Use the same rate in all communication.

        Net pay questions
        Candidates often ask how much they will receive after taxes. Net pay depends on tax withholding, deductions and personal choices. Do not calculate it. Refer them to payroll.

        Practical example
        A candidate expects a higher rate than the approved range. You explain the approved range honestly and mention the twelve-month duration and the hybrid location. She asks whether you can increase it. You say you will check with your lead. Your lead confirms there is no flexibility. You inform her, and she decides not to proceed. You thank her and record her expectations for future roles.

        Recruiter checklist
        Know the approved range before the call.
        Ask about expectations openly.
        Share only approved rates and explanations.
        Record the agreed rate accurately.

        Common mistakes
        Promising a rate before approval.
        Sharing bill rates or margins.
        Calculating net pay for candidates.

        Key takeaway
        Transparent, approved and accurately recorded rates prevent disputes and build trust.
