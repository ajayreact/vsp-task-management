        Specific: mention the role, location and work mode.
        Honest: introduce yourself and your company.
        Short: four or five sentences.
        Clear question: Would you be open to a short call?

        Follow-up messages
        Wait a few days before following up.
        Follow up once or twice, then stop.
        Example: Hello Priya, just following up on my message about the Java role in Charlotte. If you are not looking right now, no problem at all.

        Moving to other channels
        When a candidate is interested, ask for their preferred phone number and email for the call and job description.
        Move formal communication to official email.

        What not to do on LinkedIn
        Do not send the same message to hundreds of people.
        Do not ask for documents through LinkedIn messages.
        Do not discuss detailed rates or immigration matters in public posts or comments.
        Do not argue with candidates or comment negatively about other companies.

        Your LinkedIn profile
        Use your real name, a professional photo, your title and your company.
        Add a short summary explaining what kind of roles you recruit for.
        Keep it consistent with your email signature.

        Practical example
        A candidate replies to your message: Is this a real job? You reply: Yes, it is a current Java developer role with a banking client in Charlotte. You can see my company on my profile. If you share your email, I will send the job description from my official company address. You then follow through by email.

        Recruiter checklist
        Write personal, short, honest messages.
        Follow up politely, at most twice.
        Move formal communication to email.
        Keep your profile professional.

        Common mistakes
        Generic copy-and-paste messages.
        Repeated follow-ups that feel like pressure.
        Requesting documents on LinkedIn.

        Key takeaway
        On LinkedIn, personal and respectful communication earns replies. Spam earns blocks.
