        Learning objective
        Write clear, professional emails to candidates and vendors that are easy to read, accurate and appropriate.

        What you need to know
        Email is the main written channel in U.S. staffing. It creates records of agreements, submissions and important information. A well-written email saves time and builds credibility. A careless email can cause confusion or even compliance problems.

        Structure of a professional email
        A clear subject line, for example Java Developer, Charlotte, submission.
        A polite greeting, such as Dear Rahul, or Hello Rahul.
        A short opening sentence explaining the purpose.
        The main details, in short paragraphs.
        A clear request or next step.
        A professional closing and full signature.

        Writing style
        Short sentences and paragraphs.
        Simple, polite words.
        Correct spelling and grammar. Read your email before sending.
        Dates with month names and times with time zones.
        No slang, emojis or text abbreviations.

        Emails to candidates
        Role summaries and job descriptions.
        Interest confirmation and RTR requests.
        Interview confirmations with date, time, time zone and link.
        Updates and feedback.

        Emails to vendors
        Submissions with an accurate candidate summary.
        Follow-ups on feedback.
        Interview scheduling.
        Keep them concise. Vendors receive many emails.

        Privacy and security
        Never send sensitive documents to personal or unknown addresses.
        Do not include candidates' sensitive information in subject lines.
        Use blind copy only when appropriate, and never expose one candidate's details to another.
        Follow your company's rules for sending documents.

        Sample interview confirmation
        Subject: Interview confirmed, Thursday, June 4, 11 a.m. Eastern.
        Dear Priya, your video interview with the client is confirmed for Thursday, June 4, at 11 a.m. Eastern Time, which is 8:30 p.m. India Standard Time if you are calling from India. The meeting link is below. Please join five minutes early with your camera on, from a quiet place. Best of luck. Anita.

        Practical example
        You are about to send a submission email to a vendor. Before sending, you check the candidate's name, location, work authorization summary, rate and availability against your notes. You notice that you typed Dallas instead of Austin. You correct it and send.

        Recruiter checklist
        Use clear subject lines and structure.
        Check every detail before sending.
        Include dates, times and time zones.
        Protect sensitive information.

        Common mistakes
        Vague subject lines.
        Long, unstructured paragraphs.
        Sending documents insecurely.

        Key takeaway
        A clear, accurate and secure email is a professional record. Write it carefully and check it before sending.
