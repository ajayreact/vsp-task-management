        Recruiter checklist
        Ask about current project and end date.
        Understand the reason for change.
        Respect current commitments.
        Refer status and agreement questions appropriately.

        Common mistakes
        Encouraging candidates to quit without notice.
        Criticising current employers.
        Interpreting agreements or OPT rules.

