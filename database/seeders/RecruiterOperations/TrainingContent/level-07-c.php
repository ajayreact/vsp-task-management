        'Candidate Communication' => <<<'TEXT'
        Learning objective
        Use clear, respectful and effective communication skills on calls, especially active listening, clarity and tone.

        What you need to know
        Level 6 explained the principles of candidate communication across the process. This lesson focuses on communication skills during calls. Good calling communication is a skill you can practise and improve every day.

        Active listening
        Let the candidate finish before you speak.
        Show that you are listening with short responses, such as I see, or That makes sense.
        Summarise what you heard: So, you prefer hybrid roles in Texas, and you can start in July. Is that right?
        Ask follow-up questions based on what they said, not just the next question on your list.

        Clarity
        Use short sentences.
        Avoid jargon or explain it simply.
        Repeat important details, such as dates, rates and times.
        Spell names and email addresses when needed.

        Tone
        Warm and polite, even when the candidate is not interested.
        Calm and confident, especially on sensitive topics such as visas and rates.
        Respectful of the candidate's experience and choices.

        Clear English for international calls
        Speak at a steady pace.
        Pronounce numbers carefully, for example fifteen and fifty.
        Avoid local idioms. Instead of prepone, say move earlier. Instead of do the needful, say please complete this.
        Confirm understanding by asking short questions.

        Handling difficult moments
        If the candidate is frustrated, acknowledge it: I understand that this process has taken longer than expected.
        If the candidate is rude, stay polite and end the call professionally if needed.
        If you make a mistake, admit it and correct it.

        Ending conversations well
        Summarise the next steps.
        Confirm the next contact time.
        Thank them for their time.

        Practical example
        A candidate explains, at length, why she left her previous internship. You listen without interrupting, then summarise: So, the internship ended because the project finished, and you are now looking for full-time development roles. Is that right? She confirms and seems more relaxed. The rest of the call goes smoothly.

        Recruiter checklist
        Listen actively and summarise.
        Speak clearly and repeat key details.
        Keep a warm and calm tone.
        End every call with next steps.

        Common mistakes
        Interrupting candidates.
        Talking too fast.
        Using unclear local expressions.

        Key takeaway
        Good calling communication is listening, clarity and tone. Practise them deliberately and every call improves.
