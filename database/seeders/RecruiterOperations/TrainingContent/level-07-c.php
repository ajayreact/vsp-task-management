        Communicate professionally on LinkedIn through connection requests, messages and follow-ups that respect candidates and platform rules.

        What you need to know
        LinkedIn is often the first place a candidate sees your name. Your messages there must be personal, short and professional. LinkedIn is a professional network with rules about messaging and connection behaviour. Spammy behaviour can lead to account limits and damages your company's reputation.

