        Learning objective
        Follow up after calls professionally by phone, text and email, so that candidates stay engaged and informed.

        What you need to know
        Every call should be followed by a written summary or confirmation and by timely updates. Follow-up shows reliability and keeps the candidate engaged, especially when they are speaking with several recruiters.

        Immediately after a call
        Send a short email or message within an hour.
        Thank the candidate for their time.
        Summarise the role and next steps.
        Attach the job description if you promised it.
        Include your contact details.

        Sample follow-up email
        Subject: Java Developer, Charlotte, next steps.
        Dear Rahul, thank you for speaking with me today. As discussed, this is a twelve-month W2 contract with a banking client in Charlotte, hybrid three days a week. I have attached the job description. With your confirmation, I will submit your profile today. Please reply to confirm that you are interested in this role at the rate we discussed. Best regards, Anita, OPT Recruiter.

        Follow-up schedule
        After submission: update within one or two business days.
        After an interview: call the same day for feedback, then share client feedback when you receive it.
        When there is no news: send a short update anyway.
        After the start: check in on the first day and after the first week.

        Follow-up channels
        Phone for important updates, such as interview invitations and offers.
        Email for written records and documents.
        Text messages for short reminders, if the candidate agreed to texts.
        Use only official channels approved by your company.

        Professional closing in follow-up calls
        Thank you for your time today.
        I will update you by Thursday afternoon.
        Please feel free to call me if you have any questions.

        When candidates do not respond
        Follow up two or three times, a few days apart.
        Then send a polite final message: I have not heard back, so I will assume you are not looking right now. Please contact me anytime if that changes.

        Practical example
        After an interview, you call the candidate. He says the technical round went well, but he struggled with one Kafka question. You thank him, record his feedback, and email the vendor asking for client feedback. You update the candidate the next day, even though the client has not responded yet.

        Recruiter checklist
        Send a summary after every call.
        Follow the update schedule.
        Use approved channels.
        Close every follow-up with a next step.

        Common mistakes
        Forgetting written confirmation.
        Disappearing when there is no news.
        Following up too frequently.

        Key takeaway
        Timely, written and polite follow-up keeps candidates engaged and creates a clear record of every agreement.
