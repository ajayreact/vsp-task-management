        Learning objective
        Handle candidate resumes accurately and ethically, from receipt through submission and handoff, without misrepresentation.

        What you need to know
        The resume is the main document in recruiting. It is used for screening, submission, interviews and sometimes background checks. Clients and vendors trust that the resume is accurate. Any false information can lead to rejection, termination after placement and serious damage to your company's reputation.

        Receiving resumes
        Ask candidates to send their latest resume by email or through your company's approved system.
        Save it in the approved location with a clear file name, such as candidate name, role and date.
        Note the date received, so that you always use the latest version.

        Reviewing resumes for accuracy
        Check that dates, companies, titles and education match what the candidate said on the call.
        Ask about any differences politely.
        Check that skills listed are supported by project descriptions.

        Formatting for submission
        Company-specific process: some companies use a standard submission format, such as a company header or a summary section. Follow your approved format. Verify with your lead.
        You may correct obvious formatting problems, such as spacing and fonts.
        You may add a short recruiter summary, if your process allows, based only on verified facts.

        What you must never do
        Add skills, experience, employers, titles or certifications the candidate does not have.
        Change dates to hide gaps or inflate experience.
        Change education details.
        Submit a modified resume without the candidate's review and approval.

        Resumes in the handoff
        Include the final submitted resume in the handoff to HR, so that background checks and records match.
        If the candidate updates their resume later, record the new version and inform the right team if it matters.

        Practical example
        A candidate's resume lists five years of experience, but on the call he said three. You ask politely. He explains that he included academic projects. You ask him to update the resume to separate professional experience from academic projects. He sends a corrected version, and you submit it.

        Recruiter checklist
        Use the latest resume version.
        Check resume details against the call.
        Follow the approved format.
        Never add or change facts.

        Common mistakes
        Submitting outdated resumes.
        Editing content without approval.
        Ignoring differences between resume and call.

