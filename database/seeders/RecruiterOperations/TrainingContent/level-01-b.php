        Requirement, or req, means an open job position from a client or vendor.
        Submission means sending a candidate's profile to a client or vendor for a requirement.
        Turnaround time means how quickly something must be done.
        Follow up means contacting someone again after an earlier message.
        Touch base means a short check-in conversation.
        Heads up means an early warning.
        Out of office, or OOO, means a person is away and not responding.
        Circle back means to return to a topic later.

