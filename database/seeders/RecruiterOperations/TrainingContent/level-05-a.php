        Learning objective
        Learn how U.S. job descriptions are structured and how to read them efficiently and accurately.

        What you need to know
        U.S. job descriptions follow a familiar pattern, although every company writes them differently. Most include a job title, a summary of the role, a description of the company, responsibilities, required qualifications, preferred qualifications, and sometimes pay and benefits.
        Staffing requirements often add a header from the vendor with location, duration, rate, engagement type, interview process and submission instructions. Read both the header and the description.

        From the company training material
        The Job Description Analysis training defines a job description as a written statement describing the role, its expectations and its qualifications. It helps the recruiter understand what the client needs and what the selected candidate will do. It may be used externally to attract applicants, or internally to define responsibilities. A good JD gives a clear picture of the position, the required capabilities and the working conditions.
        The recruiter's goal is to convert the JD into searchable keywords and objective screening criteria.
        The training tells you to read beyond the job title, in eight parts: the job title, the summary, the company description, the requirements or qualifications, the experience, the skills, the responsibilities, and the pay or benefits. The next eight lessons cover these parts in that order.

        How to read a JD efficiently
        First pass. Read the whole JD quickly. Ask yourself what the person will actually do every day.
        Second pass. Highlight the title, the location and work mode, the duration, the start date, and the must-have skills.
        Third pass. Look for hidden requirements, such as a domain like banking or healthcare, a certification, a specific tool version, or a phrase like local candidates only.
        Final check. Re-read the submission instructions and deadline.

        Reading the language of JDs
        Required, must have and minimum qualifications usually mean the client will reject candidates without them.
        Preferred, nice to have, plus and bonus mean helpful but not essential.
        Strong, expert and hands-on suggest depth of experience, not just familiarity.
        Exposure to or familiarity with suggests a lower level of depth is acceptable.
        Years of experience may be a guideline or a strict filter. Ask the vendor if unclear.

        Spotting problems in a JD
        A long list of unrelated technologies may mean the JD was copied from older roles. Ask which skills matter most.
        Conflicting information, such as remote in one place and onsite in another, must be clarified.
        A very low rate for a senior skill set may make the requirement hard to fill. Flag it to your lead.

        Practical example
        In the running Java Developer example, the description mentions experience with Kafka streaming pipelines in the responsibilities, but lists Kafka only as preferred. You ask the vendor whether Kafka is essential. The vendor confirms it is preferred, but candidates with it will be prioritised. You note this in your summary.

        Recruiter checklist
        Read in passes: overview, key details, hidden requirements, instructions.
        Note the difference between required and preferred.
        Clarify conflicts before sourcing.

        Common mistakes
        Reading only the vendor header and not the description.
        Missing a hidden domain or certification requirement.
        Assuming years of experience are flexible without asking.

        Key takeaway
        Read job descriptions in deliberate passes and pay attention to the language. Small words like required and preferred change everything.
